//! Generates `style/main.css` from the theme bundles in `apps/shenron/themes`.
//!
//! The crate contains no colour literal. Every bundle is loaded and validated by
//! `yolo-stack-theme`, its palettes are computed (HCT, light and dark) with the contrast gates
//! enforced, and the CSS is emitted per `:root[data-theme]`. Structural rules come from
//! `src/structure.rs` and only reference `var(--yolo-*)`.
//!
//! Side outputs:
//! - `style/contrast-audit.txt`: ratio of every gated pair, per bundle and scheme.
//! - `public/theme-assets/<sha256 prefix>.<ext>`: bundle assets under their content hash, served
//!   with `immutable` caching. In production the same files are uploaded to the CDN and
//!   `SHENRON_THEME_CDN` points the urls at it.
//!
//! The build fails if a bundle is invalid or a gate cannot be met.

use std::{
    env, fs,
    path::{Path, PathBuf},
};

use yolo_stack_theme::{
    assets::CdnConfig,
    bundle::{Registry, ThemeBundle},
    compute::compute_with,
    emit,
    gate::audit,
    prefs::UserThemePrefs,
};

#[allow(dead_code)]
mod structure {
    include!("src/structure.rs");
}

const DEFAULT_THEME: &str = "shenron";

fn load_bundle(dir: &Path) -> ThemeBundle {
    let read = |name: &str| {
        fs::read_to_string(dir.join(name))
            .unwrap_or_else(|e| panic!("{}: {e}", dir.join(name).display()))
    };
    ThemeBundle::from_strs(
        &read("theme.toml"),
        &read("bundle.toml"),
        &read("assets.lock.json"),
    )
    .unwrap_or_else(|e| panic!("{}", e))
}

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let themes_dir = manifest_dir.join("../../themes");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/structure.rs");
    println!("cargo:rerun-if-changed={}", themes_dir.display());
    println!("cargo:rerun-if-env-changed=SHENRON_THEME_CDN");

    let mut dirs: Vec<PathBuf> = fs::read_dir(&themes_dir)
        .expect("apps/shenron/themes")
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.join("theme.toml").is_file())
        .collect();
    dirs.sort();
    for dir in &dirs {
        println!("cargo:rerun-if-changed={}", dir.display());
    }
    let registry = Registry::new(dirs.iter().map(|d| load_bundle(d)).collect(), DEFAULT_THEME)
        .unwrap_or_else(|e| panic!("{e}"));

    let cdn = CdnConfig {
        base: env::var("SHENRON_THEME_CDN").unwrap_or_else(|_| "/theme-assets".to_owned()),
    };
    let assets_out = manifest_dir.join("public/theme-assets");
    fs::create_dir_all(&assets_out).expect("create public/theme-assets");

    let mut css =
        String::from("/* GENERATED by build.rs from apps/shenron/themes. Do not edit. */\n");
    let mut audit_report = String::from("bundle scheme pair kind ratio min\n");
    for (bundle, dir) in registry.all().iter().zip(&dirs) {
        let theme = compute_with(bundle, &UserThemePrefs::default(), &cdn);
        assert!(
            theme.gate.passes(),
            "{}: contrast gates failed: {:?}",
            theme.id,
            theme.gate.failures
        );
        css.push_str(&emit::css(&theme));
        css.push_str(&structure::render_layout(&theme.id, &theme.shape.layout));
        for (scheme, roles) in [("light", &theme.light), ("dark", &theme.dark)] {
            for r in audit(roles) {
                audit_report.push_str(&format!(
                    "{} {scheme} {}/{} {:?} {:.2} {:.1}\n",
                    theme.id, r.fg, r.bg, r.kind, r.ratio, r.min
                ));
            }
        }
        for (path, locked) in &bundle.lock.files {
            let ext = path.rsplit_once('.').map_or("bin", |(_, e)| e);
            let target = assets_out.join(format!("{}.{ext}", &locked.sha256[..16]));
            if !target.exists() {
                fs::copy(dir.join(path), &target)
                    .unwrap_or_else(|e| panic!("copy {} -> {}: {e}", path, target.display()));
            }
        }
    }
    css.push_str(&structure::render_structure());

    let out_dir = manifest_dir.join("style");
    fs::create_dir_all(&out_dir).expect("create style/");
    // Only rewrite when the content changed, so cargo-leptos hot-reload is not triggered.
    for (name, text) in [("main.css", css), ("contrast-audit.txt", audit_report)] {
        let out = out_dir.join(name);
        if fs::read_to_string(&out).ok().as_deref() != Some(text.as_str()) {
            fs::write(&out, text).unwrap_or_else(|e| panic!("write {name}: {e}"));
        }
    }
}
