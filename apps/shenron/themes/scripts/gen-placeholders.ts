const NOTE =
  "<!-- PLACEHOLDER: original geometric art generated by apps/shenron/themes/scripts/gen-placeholders.ts. Final art to commission. CC0-1.0. -->";

function motifPaths(motif: Motif, fill: string, stroke: string): string {
  switch (motif) {
    case "serpent":
      return `<path d="M12 50 C 12 26, 34 40, 32 22 S 52 14, 52 30 S 30 54, 44 54" fill="none" stroke="${stroke}" stroke-width="6" stroke-linecap="round"/><circle cx="50" cy="12" r="5" fill="${fill}"/>`;
    case "shell":
      return `<polygon points="32,6 54,19 54,45 32,58 10,45 10,19" fill="none" stroke="${stroke}" stroke-width="5" stroke-linejoin="round"/><polygon points="32,20 43,26 43,38 32,44 21,38 21,26" fill="${fill}"/>`;
    case "capsule":
      return `<rect x="6" y="20" width="52" height="24" rx="12" fill="none" stroke="${stroke}" stroke-width="5"/><path d="M32 20 V44" stroke="${stroke}" stroke-width="5"/><rect x="10" y="24" width="20" height="16" rx="8" fill="${fill}"/>`;
    case "spires":
      return `<path d="M10 56 Q 16 20 22 56 Z" fill="${fill}"/><path d="M26 56 Q 34 4 42 56 Z" fill="${fill}"/><path d="M46 56 Q 51 30 56 56 Z" fill="${fill}"/><path d="M6 58 H58" stroke="${stroke}" stroke-width="4" stroke-linecap="round"/>`;
  }
}

function logo(t: Theme, variant: "mark" | "mono" | "dark" | "mask"): string {
  const fill = variant === "mask" ? "#000" : variant === "dark" ? t.dark[2] : variant === "mono" ? "currentColor" : t.light[2];
  const stroke = fill;
  return `${NOTE}\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="${t.title}">${motifPaths(t.motif, fill, stroke)}</svg>\n`;
}

function wordmark(t: Theme): string {
  return `${NOTE}\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 240 48" role="img" aria-label="${t.title}"><text x="0" y="36" font-family="${t.display}, system-ui, sans-serif" font-size="34" font-weight="700" fill="currentColor">${t.title}</text></svg>\n`;
}

function pet(t: Theme): string {
  const [, , accent] = t.light;
  return `${NOTE}\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96" role="img" aria-label="${t.petName}"><ellipse cx="48" cy="86" rx="22" ry="4" fill="#000" opacity="0.15"/><g transform="translate(16 12) scale(1)">${motifPaths(t.motif, accent, accent)}</g><circle cx="38" cy="44" r="3" fill="#000"/><circle cx="58" cy="44" r="3" fill="#000"/></svg>\n`;
}

function wallpaper(t: Theme, dark: boolean, w: number, h: number, setId: string): string {
  const [a, b, c] = dark ? t.dark : t.light;
  const body =
    setId === "main"
      ? `<g transform="translate(${w * 0.62} ${h * 0.12}) scale(${h / 90})" opacity="0.28">${motifPaths(t.motif, c, c)}</g>`
      : `<g stroke="${c}" stroke-width="1" opacity="0.16">${Array.from({ length: 16 }, (_, i) => `<path d="M${(w / 16) * i} 0 V${h}"/><path d="M0 ${(h / 16) * i} H${w}"/>`).join("")}</g>`;
  return `${NOTE}\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" preserveAspectRatio="xMidYMid slice"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${a}"/><stop offset="1" stop-color="${b}"/></linearGradient></defs><rect width="${w}" height="${h}" fill="url(#g)"/>${body}</svg>\n`;
}

const SETS = [
  { id: "main", label: "Motif" },
  { id: "grid", label: "Grille" },
];
const SIZES: { min: number; w: number; h: number }[] = [
  { min: 0, w: 1280, h: 800 },
  { min: 1280, w: 2560, h: 1600 },
];

function theme_toml(t: Theme, sha: Record<string, string>): string {
  return `# ${t.name}: placeholder bundle. Format: yolo-theme-pack (yolo-ui). Colours are computed from the seed.
id = "${t.id}"
name = "${t.name}"

[title]
product_name = "${t.title}"
window_title_template = "{page} - ${t.title}"
ntp_heading = "${t.title}"

[logo]
mark = "brand/logo.svg"
monochrome = "brand/logo-mono.svg"
wordmark = "brand/wordmark.svg"

[color]
seed = "${t.seed}"
source = "seed"
variant = "${t.variant}"
contrast = ${t.contrast.toFixed(1)}
mode = "${t.mode}"

[icons]
set = "phosphor"
style = "outlined"
weight = 300

[[wallpapers]]
file = "wallpapers/main-light-1280.svg"
mode = "light"
seed = "${t.light[2]}"
license = "CC0-1.0"
source = "original"
sha256 = "${sha["wallpapers/main-light-1280.svg"]}"

[[wallpapers]]
file = "wallpapers/main-dark-1280.svg"
mode = "dark"
seed = "${t.dark[2]}"
license = "CC0-1.0"
source = "original"
sha256 = "${sha["wallpapers/main-dark-1280.svg"]}"

[pet]
id = "${t.petId}"
provider = "pack"
anchor = "${t.petAnchor}"
size = 96

[typography]
display = "${t.display}"
body = "Google Sans Flex"
mono = "Google Sans Code"

[shell]
layout = "${t.layout}"
density = ${t.density}
radius = [${t.radius.join(", ")}]
glass_blur = ${t.glassBlur}
motion = "${t.motion}"
`;
}

function files(t: Theme): string[] {
  const out = ["brand/logo.svg", "brand/logo-mono.svg", "brand/logo-dark.svg", "brand/logo-mask.svg", "brand/wordmark.svg", "pet/sprite.svg"];
  for (const s of SETS) for (const mode of ["light", "dark"]) for (const z of SIZES) out.push(`wallpapers/${s.id}-${mode}-${z.w}.svg`);
  return out;
}

function bundle_toml(t: Theme): string {
  let s = `schema = 1\n${t.headerFont ? `header_font = "${t.headerFont}"\n` : ""}\n[brand]\nlogo_dark = "brand/logo-dark.svg"\nlogo_mask = "brand/logo-mask.svg"\n\n`;
  s += `[pet]\nname = "${t.petName}"\nsprite = "pet/sprite.svg"\nidle = [${t.idle.map((i) => `"${i}"`).join(", ")}]\nbehaviors = [${t.behaviors.map((i) => `"${i}"`).join(", ")}]\n\n`;
  for (const set of SETS) {
    s += `[[wallpaper]]\nid = "${set.id}"\nlabel = "${set.label}"\n\n`;
    for (const mode of ["light", "dark"] as const) {
      const dom = (mode === "dark" ? t.dark : t.light)[0];
      for (const z of SIZES) {
        s += `[[wallpaper.variant]]\nfile = "wallpapers/${set.id}-${mode}-${z.w}.svg"\nscheme = "${mode}"\nmin_width = ${z.min}\nwidth = ${z.w}\nheight = ${z.h}\ndominant = "${dom}"\n\n`;
      }
    }
  }
  for (const f of files(t)) {
    s += `[[asset]]\nfile = "${f}"\nlicense = "CC0-1.0"\nsource = "original"\nplaceholder = true\n\n`;
  }
  return s.trimEnd() + "\n";
}

function write(path: string, text: string) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

const root = join(import.meta.dir, "..");
const manifests = process.argv.includes("--manifests");

for (const t of THEMES) {
  const dir = join(root, t.id);
  write(join(dir, "brand/logo.svg"), logo(t, "mark"));
  write(join(dir, "brand/logo-mono.svg"), logo(t, "mono"));
  write(join(dir, "brand/logo-dark.svg"), logo(t, "dark"));
  write(join(dir, "brand/logo-mask.svg"), logo(t, "mask"));
  write(join(dir, "brand/wordmark.svg"), wordmark(t));
  write(join(dir, "pet/sprite.svg"), pet(t));
  for (const s of SETS)
    for (const mode of ["light", "dark"] as const)
      for (const z of SIZES) write(join(dir, `wallpapers/${s.id}-${mode}-${z.w}.svg`), wallpaper(t, mode === "dark", z.w, z.h, s.id));
  const lock: Record<string, { sha256: string; bytes: number; mime: string }> = {};
  for (const f of files(t)) {
    const bytes = readFileSync(join(dir, f));
    lock[f] = { sha256: new Bun.CryptoHasher("sha256").update(bytes).digest("hex"), bytes: bytes.length, mime: "image/svg+xml" };
  }
  if (manifests || !existsSync(join(dir, "theme.toml"))) {
    write(join(dir, "theme.toml"), theme_toml(t, Object.fromEntries(Object.entries(lock).map(([k, v]) => [k, v.sha256]))));
    write(join(dir, "bundle.toml"), bundle_toml(t));
  }
  write(join(dir, "assets.lock.json"), JSON.stringify({ schema: 1, files: lock }, null, 2) + "\n");
  console.log(`${t.id}: ${files(t).length} files`);
}
