// Generates the Shenron theme bundles: placeholder vector art, manifests and assets.lock.json.
//
//   bun apps/shenron/themes/scripts/gen-placeholders.ts [--manifests]
//
// Without flags it rewrites the SVG assets and every assets.lock.json (sha256, size, mime).
// With --manifests it also rewrites theme.toml and bundle.toml from the table below.
//
// ALL ART HERE IS PLACEHOLDER: original geometric shapes, CC0, no Dragon Ball artwork. Each file
// carries a PLACEHOLDER comment and a `placeholder = true` record in bundle.toml. Replace with
// commissioned art, run this script without --manifests to refresh the hashes, and set the
// record to `placeholder = false` with the real licence.

