// Generates a @tanstack/react-router route tree from an `app/` scan: the root layout becomes the
// root route, every segment with a `layout` becomes a parent route rendering `Outlet`, every page a
// leaf route with a `React.lazy` component. `loading`, `error` and `not-found` files map to
// `pendingComponent`, `errorComponent` and `notFoundComponent` (nearest file in the segment chain,
// as in Next). The result is TypeScript source, served as the virtual module `yolo:route-tree`.
import type { BunPlugin } from "bun";
import type { AppRoute, AppTree, Segment, SegmentFile } from "../app/scan";

/** Virtual module name served by `routeTreePlugin`. */
export const ROUTE_TREE_MODULE = "yolo:route-tree";

export interface RenderRouteTreeOptions {
  /** Prepended to every project-relative file path in the generated imports (default `./`). */
  importPrefix?: string;
}

/**
 * Convert one Next route pattern to the TanStack path syntax: `[slug]` becomes `$slug`,
 * `[...slug]` and `[[...slug]]` become the splat `$`.
 *
 * Limitation: TanStack has no optional catch-all. Its splat already matches zero segments
 * (`/docs/$` matches `/docs`), so `[[...slug]]` and `[...slug]` produce the same `$` route and a
 * catch-all page also renders for the bare parent path. The params differ as well: the splat is
 * `_splat` (a string, `a/b`), not an array under the Next param name.
 */
export function tanstackRoutePath(pattern: string): string {
  const parts = pattern.split("/").filter(Boolean).map(tanstackSegment);
  return `/${parts.join("/")}`;
}

function tanstackSegment(raw: string): string {
  if (/^\[\[\.\.\.([^\]]+)\]\]$/.test(raw) || /^\[\.\.\.([^\]]+)\]$/.test(raw)) return "$";
  const m = /^\[([^\]]+)\]$/.exec(raw);
  if (m) return `$${m[1]}`;
  return raw;
}

/** The path of `pattern` below `parent` (both Next patterns), in TanStack syntax; `/` for the same path. */
function relativeRoutePath(parent: string, pattern: string): string {
  const parentParts = parent.split("/").filter(Boolean);
  const parts = pattern.split("/").filter(Boolean);
  const rest = parts.slice(parentParts.length);
  return rest.length ? rest.map(tanstackSegment).join("/") : "/";
}

interface LayoutRoute {
  name: string;
  segment: Segment;
  parent: LayoutRoute | undefined;
  children: string[];
}

/** Render the route tree module for `tree`. */
export function renderRouteTree(tree: AppTree, options: RenderRouteTreeOptions = {}): string {
  const prefix = options.importPrefix ?? "./";
  const importOf = (file: string) => JSON.stringify(prefix + file);
  const lazyOf = (file: string) => `lazy(() => import(${importOf(file)}))`;

  const lines: string[] = [];
  lines.push(
    `// Generated by @yolo-rs/fullstack from ${tree.appDir}/. Do not edit.`,
    `import * as React from "react";`,
    `import { Outlet, createRootRoute, createRoute, createRouter, type RouterOptions } from "@tanstack/react-router";`,
    ``,
    `type Component = React.ComponentType<any>;`,
    `const lazy = (load: () => Promise<{ default: Component }>): Component => React.lazy(load);`,
    `/** Next layouts receive \`children\`; TanStack parent routes render \`Outlet\`. */`,
    `const withOutlet = (Layout: Component): Component =>`,
    `  function LayoutRoute(props: Record<string, unknown>) {`,
    `    return React.createElement(Layout, props, React.createElement(Outlet));`,
    `  };`,
    ``,
  );

  // Nearest segment file in the chain (Next semantics: loading/error/not-found cover the subtree).
  const nearest = (chain: readonly Segment[], file: SegmentFile): string | undefined => {
    for (let i = chain.length - 1; i >= 0; i--) {
      const found = chain[i]!.files[file];
      if (found) return found;
    }
    return undefined;
  };
  const boundaries = (chain: readonly Segment[]): string[] => {
    const out: string[] = [];
    const loading = nearest(chain, "loading");
    const error = nearest(chain, "error");
    const notFound = nearest(chain, "not-found");
    if (loading) out.push(`pendingComponent: ${lazyOf(loading)}`);
    if (error) out.push(`errorComponent: ${lazyOf(error)}`);
    if (notFound) out.push(`notFoundComponent: ${lazyOf(notFound)}`);
    return out;
  };

  const root = tree.rootSegment;
  const rootChain = [root];
  const rootComponent = root.files.layout ? `withOutlet(${lazyOf(root.files.layout)})` : "Outlet";
  const rootOptions = [`component: ${rootComponent}`, `wrapInSuspense: true`, ...boundaries(rootChain)];
  if (!root.files["not-found"] && tree.notFound) rootOptions.push(`notFoundComponent: ${lazyOf(tree.notFound)}`);
  lines.push(`const rootRoute = createRootRoute({ ${rootOptions.join(", ")} });`);

  const rootLayout: LayoutRoute = {
    name: "rootRoute",
    segment: root,
    parent: undefined,
    children: [],
  };
  const layouts = new Map<string, LayoutRoute>();
  let counter = 0;

  // One parent route per segment with a layout (the root excluded), shared by every page below it.
  const layoutFor = (chain: readonly Segment[]): LayoutRoute => {
    let parent = rootLayout;
    for (let i = 1; i < chain.length; i++) {
      const segment = chain[i]!;
      if (!segment.files.layout) continue;
      const key = `${segment.path}\0${segment.files.layout}`;
      let layout = layouts.get(key);
      if (!layout) {
        const name = `layout${++counter}`;
        const path = relativeRoutePath(parent.segment.path, segment.path);
        const where = path === "/" ? `id: ${JSON.stringify(`_${name}`)}` : `path: ${JSON.stringify(path)}`;
        const opts = [
          `getParentRoute: () => ${parent.name}`,
          where,
          `component: withOutlet(${lazyOf(segment.files.layout)})`,
          ...boundaries(chain.slice(0, i + 1)),
        ];
        lines.push(`const ${name} = createRoute({ ${opts.join(", ")} });`);
        layout = { name, segment, parent, children: [] };
        layouts.set(key, layout);
        parent.children.push(name);
      }
      parent = layout;
    }
    return parent;
  };

  const pages: AppRoute[] = tree.routes.filter(route => route.kind === "page");
  for (const route of pages) {
    const chain = route.segments.length ? route.segments : rootChain;
    const parent = layoutFor(chain);
    const name = `page${++counter}`;
    const path = relativeRoutePath(parent.segment.path, route.pattern);
    const opts = [
      `getParentRoute: () => ${parent.name}`,
      `path: ${JSON.stringify(path)}`,
      `component: ${lazyOf(route.file)}`,
      ...boundaries(chain),
    ];
    lines.push(`const ${name} = createRoute({ ${opts.join(", ")} });`);
    parent.children.push(name);
  }

  const children = (layout: LayoutRoute): string => {
    const items = layout.children.map(name => {
      const nested = [...layouts.values()].find(l => l.name === name);
      return nested ? `${name}.addChildren([${children(nested)}])` : name;
    });
    return items.join(", ");
  };
  lines.push(
    ``,
    `export const routeTree = rootRoute.addChildren([${children(rootLayout)}]);`,
    ``,
    `export type AppRouter = ReturnType<typeof createAppRouter>;`,
    ``,
    `/** A router for the app tree; \`options\` override the defaults (history, context, preloading). */`,
    `export function createAppRouter(options: Partial<RouterOptions<typeof routeTree, "never">> = {}) {`,
    `  return createRouter({ routeTree, defaultPreload: "intent", ...options });`,
    `}`,
    ``,
  );
  return lines.join("\n");
}

/**
 * Serves `renderRouteTree(tree)` as the virtual module `yolo:route-tree` in `Bun.build` (and `Bun.plugin`).
 * Imports are absolute (rooted at `tree.root`) unless `importPrefix` is given: relative paths do not
 * resolve from a module in a plugin namespace.
 */
export function routeTreePlugin(tree: AppTree, options: RenderRouteTreeOptions = {}): BunPlugin {
  const namespace = "yolo-route-tree";
  const importPrefix = options.importPrefix ?? `${tree.root.replaceAll("\\", "/").replace(/\/+$/, "")}/`;
  return {
    name: "@yolo-rs/fullstack:route-tree",
    setup(build) {
      build.onResolve({ filter: /^yolo:route-tree$/ }, () => ({
        path: ROUTE_TREE_MODULE,
        namespace,
      }));
      build.onLoad({ filter: /.*/, namespace }, () => ({
        contents: renderRouteTree(tree, { ...options, importPrefix }),
        loader: "ts",
        resolveDir: tree.root,
      }));
    },
  };
}
