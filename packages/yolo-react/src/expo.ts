import { createYoloTheme, parseYoloPreset, type YoloPresetId } from "./core.ts";

export interface YoloExpoConfigOptions {
  readonly name: string;
  readonly slug: string;
  readonly version?: string;
  readonly preset?: YoloPresetId;
  readonly dark?: boolean;
  readonly bundleIdentifier?: string;
  readonly androidPackage?: string;
  readonly enableReactCompiler?: boolean;
  readonly enableTypedRoutes?: boolean;
  readonly enableRustTurboModules?: boolean;
}

export interface YoloExpoAppJson {
  readonly expo: {
    readonly name: string;
    readonly slug: string;
    readonly version: string;
    readonly orientation: "portrait" | "default";
    readonly scheme: string;
    readonly userInterfaceStyle: "automatic" | "dark" | "light";
    readonly newArchEnabled: true;
    readonly ios: {
      readonly supportsTablet: true;
      readonly bundleIdentifier: string;
    };
    readonly android: {
      readonly package: string;
      readonly edgeToEdgeEnabled: true;
    };
    readonly web: {
      readonly bundler: "metro";
      readonly output: "single" | "static" | "server";
    };
    readonly experiments: {
      readonly reactCompiler: boolean;
      readonly typedRoutes: boolean;
      readonly reactServerComponents: true;
    };
    readonly extra: {
      readonly yoloEngine: "bun+rust";
      readonly yoloThemePreset: string;
      readonly yoloThemeSeed: string;
      readonly facetpackOxc: true;
      readonly uniffiRustTurboModules: boolean;
    };
  };
}

/* @__PURE__ */
export function createYoloExpoConfig(
  options: YoloExpoConfigOptions,
): YoloExpoAppJson {
  const preset = parseYoloPreset(options.preset ?? "neutral");
  const theme = createYoloTheme(preset, options.dark ?? true);
  return {
    expo: {
      name: options.name,
      slug: options.slug,
      version: options.version ?? "0.8.0",
      orientation: "default",
      scheme:
        options.slug.replace(/[^a-z0-9]/gi, "").toLowerCase() || "yoloapp",
      userInterfaceStyle: "automatic",
      newArchEnabled: true,
      ios: {
        supportsTablet: true,
        bundleIdentifier:
          options.bundleIdentifier ?? `org.yolo.${options.slug}`,
      },
      android: {
        package:
          options.androidPackage ??
          `org.yolo.${options.slug.replace(/-/g, "_")}`,
        edgeToEdgeEnabled: true,
      },
      web: {
        bundler: "metro",
        output: "server",
      },
      experiments: {
        reactCompiler: options.enableReactCompiler ?? true,
        typedRoutes: options.enableTypedRoutes ?? true,
        reactServerComponents: true,
      },
      extra: {
        yoloEngine: "bun+rust",
        yoloThemePreset: theme.canonicalId,
        yoloThemeSeed: theme.seedHex,
        facetpackOxc: true,
        uniffiRustTurboModules: options.enableRustTurboModules ?? true,
      },
    },
  };
}

/**
 * Generates a `metro.config.ts` file configured with `@ecrindigital/facetpack` (Rust OXC)
 * replacing Babel in Expo / React Native, plus `.wasm` and `.udl` UniFFI asset extensions.
 */
export function createYoloMetroFacetpackConfig(
  presetInput: YoloPresetId | string = "neutral",
): string {
  const preset = parseYoloPreset(presetInput);
  const theme = createYoloTheme(preset, true);
  return `// AUTO-GENERATED by @yolo-rs/react (bun react:patch-expo)
// Purges Babel in favor of Rust OXC (@ecrindigital/facetpack) + UniFFI Rust TurboModules
import { getDefaultConfig } from "expo/metro-config";
import { withFacetpack } from "@ecrindigital/facetpack";

const config = getDefaultConfig(import.meta.dir);

// Register Rust WASM & UniFFI interface definitions
config.resolver.assetExts = Array.from(new Set([...(config.resolver.assetExts ?? []), "wasm", "udl"]));
config.resolver.sourceExts = Array.from(new Set([...(config.resolver.sourceExts ?? []), "ts", "tsx", "mjs", "cjs"]));

export const yoloMetroMetadata = {
  runtime: "bun@1.4.4",
  transformer: "rust-oxc-facetpack",
  themePreset: "${theme.canonicalId}",
  themeSeed: "${theme.seedHex}",
  uniffiTurboModuleCrate: "yolo-react",
} as const;

export default withFacetpack(config, {
  jsxRuntime: "automatic",
  reactFastRefresh: true,
  dropConsoleInProd: false,
});
`;
}

export interface NodePurgeResult {
  readonly purgedPkg: Record<string, unknown>;
  readonly rewrittenScripts: Record<string, { before: string; after: string }>;
  readonly removedFields: string[];
}

/**
 * Rewrites a `package.json` object to purge `npm`, `yarn`, `pnpm`, `npx`, `pnpx`, `node`, `ts-node`, and `tsx`
 * in favor of `bun` and `bunx` (`bun@1.4.4`).
 */
export function purgeNodeFromPackageJson(
  rawPkg: Record<string, unknown>,
): NodePurgeResult {
  const cloned = structuredClone(rawPkg) as Record<string, unknown>;
  const rewrittenScripts: Record<string, { before: string; after: string }> =
    {};
  const removedFields: string[] = [];

  cloned.packageManager = "bun@1.4.4";
  cloned.engines = { bun: ">=1.4.4" };

  if (cloned.scripts && typeof cloned.scripts === "object") {
    const scripts = cloned.scripts as Record<string, string>;
    for (const [name, cmd] of Object.entries(scripts)) {
      if (typeof cmd !== "string") continue;
      const updated = cmd
        .replace(
          /\b(?:npx\s+|bunx\s+)?expo\s+start\b/g,
          "bunx --bun expo start",
        )
        .replace(/\bnpm\s+run\b/g, "bun run")
        .replace(/\bnpm\s+install\b/g, "bun install")
        .replace(/\bnpm\s+test\b/g, "bun test")
        .replace(/\byarn\s+dlx\b/g, "bunx")
        .replace(/\bpnpx\b/g, "bunx")
        .replace(/\bnpx\b/g, "bunx")
        .replace(/\byarn\s+run\b/g, "bun run")
        .replace(/\bpnpm\s+run\b/g, "bun run")
        .replace(/\byarn\b(?!\s*\.)/g, "bun")
        .replace(/\bpnpm\b/g, "bun")
        .replace(/\bts-node\b/g, "bun")
        .replace(/\btsx\b/g, "bun")
        .replace(/\bnode\b/g, "bun");

      if (updated !== cmd) {
        rewrittenScripts[name] = { before: cmd, after: updated };
        scripts[name] = updated;
      }
    }
  }

  for (const legacyField of ["volta", "npm", "pnpm", "yarn"]) {
    if (legacyField in cloned) {
      delete cloned[legacyField];
      removedFields.push(legacyField);
    }
  }

  return {
    purgedPkg: cloned,
    rewrittenScripts,
    removedFields,
  };
}
