import { basename, join, resolve } from "node:path";
import { rm } from "node:fs/promises";
import {
  buildYoloReactApp,
  createYoloExpoConfig,
  createYoloMetroFacetpackConfig,
  createYoloTheme,
  parseYoloPreset,
  purgeNodeFromPackageJson,
  YOLO_PRESET_IDS,
  type YoloPresetId,
} from "../packages/yolo-react/src/index.ts";

const ROOT_DIR = resolve(import.meta.dir, "..");

export type YoloReactTemplate = "web" | "expo" | "universal" | "tauri";

export interface CreateReactAppOptions {
  readonly targetDir: string;
  readonly template?: YoloReactTemplate;
  readonly preset?: YoloPresetId;
}

export interface CreateReactAppResult {
  readonly targetDir: string;
  readonly appName: string;
  readonly template: YoloReactTemplate;
  readonly preset: YoloPresetId;
  readonly createdFiles: string[];
}

export async function scaffoldYoloReactApp(
  options: CreateReactAppOptions,
): Promise<CreateReactAppResult> {
  const absDir = resolve(options.targetDir);
  const appName =
    basename(absDir)
      .toLowerCase()
      .replace(/[^a-z0-9-_]/g, "-") || "yolo-react-app";
  const template: YoloReactTemplate = options.template ?? "universal";
  const preset: YoloPresetId = parseYoloPreset(options.preset ?? "neutral");
  const theme = createYoloTheme(preset, true);
  const createdFiles: string[] = [];

  const writeTracked = async (relPath: string, content: string) => {
    const full = join(absDir, relPath);
    await Bun.write(full, content);
    createdFiles.push(relPath);
  };

  const pkgJson = {
    name: appName,
    version: "0.8.0",
    private: true,
    type: "module",
    sideEffects: false,
    packageManager: "bun@1.4.4",
    engines: {
      bun: ">=1.4.4",
    },
    scripts: {
      dev: "bun run src/server.ts",
      build: "bun run src/build.ts",
      check: "bun check",
      test: "bun test",
      ...(template === "expo" || template === "universal"
        ? {
            "expo:start": "bunx --bun expo start",
            "expo:ios": "bunx --bun expo run:ios",
            "expo:android": "bunx --bun expo run:android",
          }
        : {}),
      ...(template === "tauri"
        ? {
            "tauri:dev": "cargo tauri dev",
            "tauri:build": "cargo tauri build",
          }
        : {}),
    },
    dependencies: {
      "@yolo-rs/react": "workspace:*",
      react: "^19.1.0",
      "react-dom": "^19.1.0",
      ...(template === "expo" || template === "universal"
        ? {
            expo: "~53.0.0",
            "react-native": "0.79.0",
            "@ecrindigital/facetpack": "^0.4.0",
          }
        : {}),
    },
  };

  await writeTracked("package.json", JSON.stringify(pkgJson, null, 2) + "\n");
  await writeTracked("yolo-theme.css", theme.cssText);

  await writeTracked(
    "src/App.tsx",
    `// Generated by bun react:create (${template} / ${theme.canonicalId})
import { Button, Card, createYoloTheme } from "@yolo-rs/react";

export const activeTheme = createYoloTheme("${preset}", true);

export function App() {
  const card = Card({ variant: "elevated", theme: activeTheme });
  const cta = Button({ variant: "filled", size: "lg", label: "Launch Rust + Bun Action", theme: activeTheme });
  return {
    theme: activeTheme.canonicalId,
    cardProps: card.domProps,
    buttonProps: cta.domProps,
    nativeCardProps: card.nativeProps,
    nativeButtonProps: cta.nativeProps,
  };
}
`,
  );

  await writeTracked(
    "src/server.ts",
    `// 100% Native Bun.serve Fullstack React 19 RSC + SSR Server
import { createYoloReactServer } from "@yolo-rs/react";

const server = createYoloReactServer({
  appId: "org.yolo.${appName}",
  title: "${appName}",
  preset: "${preset}",
  dark: true,
  port: Number(Bun.env.PORT ?? 3000),
});

if (import.meta.main) {
  const instance = server.start();
  console.log(\`[yolo-react] Listening on http://\${instance.hostname}:\${instance.port} (${theme.canonicalId})\`);
}

export default server;
`,
  );

  if (template === "expo" || template === "universal") {
    const expoJson = createYoloExpoConfig({
      name: appName,
      slug: appName,
      preset,
      dark: true,
    });
    await writeTracked("app.json", JSON.stringify(expoJson, null, 2) + "\n");
    await writeTracked(
      "metro.config.ts",
      createYoloMetroFacetpackConfig(preset),
    );
  }

  return {
    targetDir: absDir,
    appName,
    template,
    preset,
    createdFiles,
  };
}

export interface PurgeDirectoryResult {
  readonly targetDir: string;
  readonly packageJsonModified: boolean;
  readonly rewrittenScripts: Record<string, { before: string; after: string }>;
  readonly removedLockfiles: string[];
}

export async function purgeNodeInDirectory(
  targetDir: string,
): Promise<PurgeDirectoryResult> {
  const absDir = resolve(targetDir);
  const pkgPath = join(absDir, "package.json");
  const pkgFile = Bun.file(pkgPath);

  let packageJsonModified = false;
  let rewrittenScripts: Record<string, { before: string; after: string }> = {};

  if (await pkgFile.exists()) {
    const raw = (await pkgFile.json()) as Record<string, unknown>;
    const purged = purgeNodeFromPackageJson(raw);
    rewrittenScripts = purged.rewrittenScripts;
    if (
      Object.keys(rewrittenScripts).length > 0 ||
      purged.removedFields.length > 0 ||
      raw.packageManager !== "bun@1.4.4"
    ) {
      await Bun.write(
        pkgPath,
        JSON.stringify(purged.purgedPkg, null, 2) + "\n",
      );
      packageJsonModified = true;
    }
  }

  const removedLockfiles: string[] = [];
  for (const legacyFile of [
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    ".npmrc",
    ".yarnrc.yml",
  ]) {
    const candidate = join(absDir, legacyFile);
    if (await Bun.file(candidate).exists()) {
      await rm(candidate, { force: true });
      removedLockfiles.push(legacyFile);
    }
  }

  return {
    targetDir: absDir,
    packageJsonModified,
    rewrittenScripts,
    removedLockfiles,
  };
}

export interface PatchExpoResult {
  readonly targetDir: string;
  readonly preset: YoloPresetId;
  readonly metroConfigPath: string;
  readonly appJsonPath: string;
  readonly turboModuleDtsPath: string;
}

export async function patchExpoDirectory(
  targetDir: string,
  presetInput: YoloPresetId | string = "neutral",
): Promise<PatchExpoResult> {
  const absDir = resolve(targetDir);
  const preset = parseYoloPreset(presetInput);
  const appName =
    basename(absDir)
      .toLowerCase()
      .replace(/[^a-z0-9-_]/g, "-") || "yolo-expo-app";

  const metroConfigPath = join(absDir, "metro.config.ts");
  const appJsonPath = join(absDir, "app.json");
  const turboModuleDtsPath = join(absDir, "yolo-rust-bridge.d.ts");

  await Bun.write(metroConfigPath, createYoloMetroFacetpackConfig(preset));
  const appJson = createYoloExpoConfig({
    name: appName,
    slug: appName,
    preset,
    dark: true,
  });
  await Bun.write(appJsonPath, JSON.stringify(appJson, null, 2) + "\n");

  const dts = `// AUTO-GENERATED by bun react:patch-expo — UniFFI & C++ JSI TurboModule Spec for crates/yolo-react
export interface YoloRustTurboModule {
  computeRnLayoutJson(treeJson: string, width: number, height: number): string;
  exportThemeReactNativeJson(preset: string, dark: boolean): string;
  encodeRscFlightPayload(treeJson: string): string;
}
export declare const YoloRustBridge: YoloRustTurboModule;
`;
  await Bun.write(turboModuleDtsPath, dts);

  return {
    targetDir: absDir,
    preset,
    metroConfigPath,
    appJsonPath,
    turboModuleDtsPath,
  };
}

export interface YoloReactEngineStatus {
  readonly runtime: string;
  readonly cratesPresent: {
    readonly yoloReact: boolean;
    readonly yoloLayout: boolean;
    readonly yoloTokens: boolean;
    readonly yoloMigrator: boolean;
    readonly yoloShared: boolean;
  };
  readonly packagesPresent: {
    readonly yoloReactPkg: boolean;
  };
  readonly docsPresent: boolean;
  readonly supportedPresets: readonly YoloPresetId[];
  readonly submodulesTracked: Record<string, boolean>;
}

export async function getYoloReactStatus(): Promise<YoloReactEngineStatus> {
  const check = async (rel: string) =>
    await Bun.file(join(ROOT_DIR, rel)).exists();

  const submodulePaths = [
    "submodules/react",
    "submodules/react-native",
    "submodules/react-strict-dom",
    "submodules/expo",
    "submodules/expo-ibex",
    "submodules/oxc",
    "submodules/facetpack",
    "submodules/uniffi-react-native",
    "submodules/rozenite",
    "submodules/tuono",
  ];
  const submodulesTracked: Record<string, boolean> = {};
  for (const sub of submodulePaths) {
    submodulesTracked[sub] =
      (await check(`${sub}/package.json`)) ||
      (await check(`${sub}/Cargo.toml`)) ||
      (await check(`${sub}/README.md`));
  }

  return {
    runtime: `bun@${Bun.version}`,
    cratesPresent: {
      yoloReact: await check("crates/yolo-react/Cargo.toml"),
      yoloLayout: await check("crates/yolo-layout/Cargo.toml"),
      yoloTokens: await check("crates/yolo-tokens/Cargo.toml"),
      yoloMigrator: await check("crates/yolo-migrator/Cargo.toml"),
      yoloShared: await check("crates/yolo-shared/Cargo.toml"),
    },
    packagesPresent: {
      yoloReactPkg: await check("packages/yolo-react/package.json"),
    },
    docsPresent: await check("docs/YOLO-REACT-AND-EXPO-BUN-RUST.md"),
    supportedPresets: YOLO_PRESET_IDS,
    submodulesTracked,
  };
}

function parseFlag(args: string[], flag: string): string | undefined {
  const idx = args.indexOf(flag);
  if (idx !== -1 && idx + 1 < args.length) {
    return args[idx + 1];
  }
  return undefined;
}

if (import.meta.main) {
  const args = Bun.argv.slice(2);
  const command = args[0] ?? "status";

  if (command === "status") {
    const status = await getYoloReactStatus();
    console.log(JSON.stringify(status, null, 2));
  } else if (command === "create") {
    const targetDir = args[1];
    if (!targetDir) {
      console.error(
        "Usage: bun run scripts/react-bun.ts create <app-dir> [--template web|expo|universal|tauri] [--preset neutral|m3|fluent|apple|omarchy|hyprland|aphrody|chromium]",
      );
      process.exit(1);
    }
    const template = (parseFlag(args, "--template") ??
      "universal") as YoloReactTemplate;
    const preset = parseYoloPreset(parseFlag(args, "--preset") ?? "neutral");
    const res = await scaffoldYoloReactApp({ targetDir, template, preset });
    console.log(JSON.stringify(res, null, 2));
  } else if (command === "purge-node") {
    const targetDir = args[1] ?? ROOT_DIR;
    const res = await purgeNodeInDirectory(targetDir);
    console.log(JSON.stringify(res, null, 2));
  } else if (command === "patch-expo") {
    const targetDir = args[1] ?? ROOT_DIR;
    const preset = parseYoloPreset(parseFlag(args, "--preset") ?? "neutral");
    const res = await patchExpoDirectory(targetDir, preset);
    console.log(JSON.stringify(res, null, 2));
  } else if (command === "build") {
    const entry = args[1] ?? join(ROOT_DIR, "packages/yolo-react/src/index.ts");
    const outdir =
      parseFlag(args, "--outdir") ?? join(ROOT_DIR, "dist/yolo-react");
    const preset = parseYoloPreset(parseFlag(args, "--preset") ?? "neutral");
    const res = await buildYoloReactApp({
      entrypoints: [resolve(entry)],
      outdir: resolve(outdir),
      preset,
    });
    console.log(JSON.stringify(res, null, 2));
    if (!res.success) process.exit(1);
  } else {
    console.error(
      `Unknown command: ${command}. Expected: create | purge-node | patch-expo | build | status`,
    );
    process.exit(1);
  }
}
