/// Dependencies dropped from the original `package.json` (replaced by `@yolo-rs/next`).
fn is_next_dependency(name: &str) -> bool {
    name == "next"
        || name == "eslint-config-next"
        || name.starts_with("@next/")
        || name == "react"
        || name == "react-dom"
        || name == "@types/react"
        || name == "@types/react-dom"
}

/// Original dependency maps (best effort; empty when `package.json` is unreadable).
fn original_dependencies(root: &str) -> (Map<String, Value>, Map<String, Value>) {
    let Ok(text) = fs::read_to_string(Path::new(root).join("package.json")) else {
        return (Map::new(), Map::new());
    };
    let Ok(value) = serde_json::from_str::<Value>(&text) else {
        return (Map::new(), Map::new());
    };
    let take = |key: &str| {
        value
            .get(key)
            .and_then(Value::as_object)
            .map(|m| {
                m.iter()
                    .filter(|(name, _)| !is_next_dependency(name))
                    .map(|(k, v)| (k.clone(), v.clone()))
                    .collect()
            })
            .unwrap_or_default()
    };
    (take("dependencies"), take("devDependencies"))
}

fn package_json(analysis: &ProjectAnalysis) -> String {
    let (mut dependencies, mut dev_dependencies) = original_dependencies(&analysis.root);
    for (name, version) in [
        ("@yolo-rs/next", "^0.1.0"),
        ("react", "^19.3.1"),
        ("react-dom", "^19.3.1"),
        ("@tanstack/react-router", "^1.170.0"),
        ("@tanstack/react-query", "^5.106.0"),
    ] {
        dependencies.insert(name.to_owned(), Value::String(version.to_owned()));
    }
    for (name, version) in [
        ("@types/bun", "^1.4.4"),
        ("@types/react", "^19.2.0"),
        ("@types/react-dom", "^19.2.0"),
        ("typescript", "^5.9.0"),
    ] {
        dev_dependencies
            .entry(name.to_owned())
            .or_insert_with(|| Value::String(version.to_owned()));
    }
    let sorted = |map: Map<String, Value>| -> Value {
        Value::Object(
            map.into_iter()
                .collect::<BTreeMap<_, _>>()
                .into_iter()
                .collect(),
        )
    };
    pretty(&json!({
        "name": analysis.name,
        "private": true,
        "type": "module",
        "scripts": {
            "dev": "bun --hot src/server.ts",
            "build": "bun run src/build.ts",
            "start": "NODE_ENV=production bun src/server.ts",
            "export": "bun run src/build.ts --export",
            "test": "bun test"
        },
        "dependencies": sorted(dependencies),
        "devDependencies": sorted(dev_dependencies),
        "packageManager": "bun@1.4.4",
        "engines": { "bun": ">=1.4.4" }
    }))
}

