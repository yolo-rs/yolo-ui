/// Emits the Bun + `TanStack` project.
pub fn emit_bun_project(analysis: &ProjectAnalysis) -> Vec<EmittedFile> {
    let mut files = Vec::new();
    let mut push = |path: &str, contents: String| {
        files.push(EmittedFile { path: path.to_owned(), contents });
    };
    let yolo = &analysis.yolo_config;
    push("yolo.config.ts", config::yolo_config_ts(yolo));
    push("bunfig.toml", turbopack::bunfig_toml(&yolo.bundler, yolo));
    push(
        "yolo.bundler.ts",
        turbopack::bundler_plugins_ts(&yolo.bundler),
    );
    push("package.json", package_json(analysis));
    push("tsconfig.json", TSCONFIG_JSON.to_owned());
    push("src/server.ts", SERVER_TS.to_owned());
    push("src/build.ts", BUILD_TS.to_owned());
    push("src/routeTree.gen.ts", route_tree_ts(analysis));
    push(
        ".yolo/routes-manifest.json",
        pretty(&routes::routes_manifest_json(
            &analysis.routes,
            &analysis.config,
        )),
    );
    push(
        ".yolo/app-paths-manifest.json",
        pretty(&routes::app_paths_manifest_json(&analysis.routes)),
    );
    push(
        ".yolo/route-manifest.json",
        pretty(&serde_json::to_value(&analysis.routes).unwrap_or(Value::Null)),
    );
    push(
        ".yolo/rules-manifest.json",
        pretty(&rules::rules_manifest_json(&analysis.config)),
    );
    push(
        ".yolo/fonts.json",
        pretty(&fonts::fonts_manifest_json(&analysis.font_plans)),
    );
    if let Some(policy) = &yolo.images {
        push(
            ".yolo/images.json",
            pretty(&images::images_manifest_json(policy)),
        );
    }
    push(
        ".yolo/client-manifest.json",
        pretty(&rsc::client_manifest_json(&analysis.graph)),
    );
    push(
        ".yolo/server-reference-manifest.json",
        pretty(&rsc::server_manifest_json(&analysis.graph)),
    );
    push(
        "src/flight-modules.ts",
        rsc::flight_bootstrap_ts(&analysis.graph),
    );
    if let Some(spec) = &analysis.proxy {
        push("src/proxy.ts", proxy::emit_bun_proxy(spec));
    }
    if !analysis.cdn.asset_prefix.is_empty() || analysis.cdn.upload.is_some() {
        push(
            "scripts/cdn-upload.ts",
            cdn::upload_script_ts(&analysis.cdn),
        );
    }
    if !analysis.font_plans.is_empty() {
        push("src/fonts.css", fonts_css(analysis));
        push("src/fonts.ts", fonts_ts(analysis));
    }
    push(".env.example", env_example(analysis));
    push("README.md", readme(analysis));
    files
}

/// Pretty JSON with a trailing newline.
fn pretty(value: &Value) -> String {
    let mut text = serde_json::to_string_pretty(value).unwrap_or_default();
    text.push('\n');
    text
}

/// JavaScript string literal (double quoted, JSON escaping).
fn js_str(text: &str) -> String {
    serde_json::to_string(text).unwrap_or_else(|_| String::from("\"\""))
}

