/// Identifier piece of one path segment (`[slug]` -> `Slug`, `(marketing)` -> `Marketing`).
fn ident_piece(segment: &str) -> String {
    let mut out = String::new();
    let mut upper = true;
    for c in segment.chars() {
        if c.is_ascii_alphanumeric() {
            if upper {
                out.extend(c.to_uppercase());
            } else {
                out.push(c);
            }
            upper = false;
        } else {
            upper = true;
        }
    }
    out
}

/// `Blog_Slug` from `/blog/[slug]`; `Index` for `/`.
fn ident_from_url(url_pattern: &str) -> String {
    let pieces: Vec<String> = url_pattern
        .split('/')
        .filter(|s| !s.is_empty())
        .map(ident_piece)
        .filter(|s| !s.is_empty())
        .collect();
    if pieces.is_empty() {
        String::from("Index")
    } else {
        pieces.join("_")
    }
}

/// `Blog_Slug` from the directory parts of a file below the app dir; `Root` at the root.
fn ident_from_file(app_dir: &str, file: &str) -> String {
    let pieces: Vec<String> = routes::app_relative_dir_parts(app_dir, file)
        .iter()
        .map(|p| ident_piece(p))
        .filter(|s| !s.is_empty())
        .collect();
    if pieces.is_empty() {
        String::from("Root")
    } else {
        pieces.join("_")
    }
}

/// Import specifier of a project file from `src/` (extension stripped).
fn import_path(file: &str) -> String {
    let without_ext = file.rsplit_once('.').map_or(file, |(stem, _)| stem);
    format!("../{without_ext}")
}

/// Unique identifier registry.
#[derive(Default)]
struct Names {
    used: BTreeSet<String>,
}

impl Names {
    fn unique(&mut self, base: &str) -> String {
        let mut candidate = base.to_owned();
        let mut n = 2;
        while !self.used.insert(candidate.clone()) {
            candidate = format!("{base}_{n}");
            n += 1;
        }
        candidate
    }
}

/// Imports keyed by file path (one import per module).
#[derive(Default)]
struct Imports {
    by_file: BTreeMap<String, String>,
    lines: Vec<String>,
}

impl Imports {
    fn component(&mut self, names: &mut Names, role: &str, base: &str, file: &str) -> String {
        if let Some(existing) = self.by_file.get(file) {
            return existing.clone();
        }
        let ident = names.unique(&format!("{role}_{base}"));
        self.lines.push(format!(
            "import {ident} from {};",
            js_str(&import_path(file))
        ));
        self.by_file.insert(file.to_owned(), ident.clone());
        ident
    }
}

/// One layout level of the `TanStack` tree.
struct LayoutNode<'a> {
    file: Option<&'a str>,
    var: String,
    tanstack_prefix: String,
    items: Vec<TreeItem<'a>>,
}

enum TreeItem<'a> {
    Page(&'a RouteEntry),
    Layout(LayoutNode<'a>),
}

impl<'a> LayoutNode<'a> {
    fn child_layout(&mut self, file: &'a str) -> &mut LayoutNode<'a> {
        let index = self
            .items
            .iter()
            .position(|item| matches!(item, TreeItem::Layout(node) if node.file == Some(file)));
        let index = index.unwrap_or_else(|| {
            self.items.push(TreeItem::Layout(LayoutNode {
                file: Some(file),
                var: String::new(),
                tanstack_prefix: String::new(),
                items: Vec::new(),
            }));
            self.items.len() - 1
        });
        match &mut self.items[index] {
            TreeItem::Layout(node) => node,
            TreeItem::Page(_) => unreachable!("index points at a layout node"),
        }
    }
}

/// Pages that belong in the navigation tree (no slot / intercept entries).
fn tree_pages(manifest: &RouteManifest) -> Vec<&RouteEntry> {
    manifest
        .entries
        .iter()
        .filter(|e| e.kind == RouteKind::Page && e.slot.is_none())
        .collect()
}

/// Builds the layout tree from the page entries.
fn build_tree<'a>(manifest: &'a RouteManifest, app_dir: &str) -> LayoutNode<'a> {
    let mut root = LayoutNode {
        file: manifest.root_layout.as_deref(),
        var: String::from("rootRoute"),
        tanstack_prefix: String::new(),
        items: Vec::new(),
    };
    for page in tree_pages(manifest) {
        let mut node = &mut root;
        for layout in page
            .layouts
            .iter()
            .filter(|l| manifest.root_layout.as_ref() != Some(l))
        {
            node = node.child_layout(layout);
            if node.tanstack_prefix.is_empty() && node.var.is_empty() {
                let prefix = routes::file_url_prefix(app_dir, layout);
                node.tanstack_prefix = if prefix.is_empty() {
                    String::new()
                } else {
                    routes::to_tanstack_path(&prefix)
                };
            }
        }
        node.items.push(TreeItem::Page(page));
    }
    root
}

/// Path of `full` relative to `prefix` (`/` when equal).
fn relative_path(full: &str, prefix: &str) -> String {
    let rest = full.strip_prefix(prefix).unwrap_or(full);
    if rest.is_empty() {
        String::from("/")
    } else if rest.starts_with('/') {
        rest.to_owned()
    } else {
        format!("/{rest}")
    }
}

/// Slot names owned by each layout file (`layout.tsx` -> `["modal"]`).
fn layout_slots(manifest: &RouteManifest) -> BTreeMap<String, Vec<String>> {
    let mut out = BTreeMap::new();
    if let Some(tree) = &manifest.tree {
        let mut stack = vec![tree];
        while let Some(segment) = stack.pop() {
            if let Some(layout) = &segment.files.layout {
                let slots: Vec<String> = segment
                    .children
                    .iter()
                    .filter(|c| c.kind == SegmentKind::ParallelSlot)
                    .map(|c| c.name.trim_start_matches('@').to_owned())
                    .collect();
                out.insert(layout.clone(), slots);
            }
            stack.extend(segment.children.iter());
        }
    }
    out
}

/// Code generation state for `routeTree.gen.ts`.
struct TreeGen<'a> {
    manifest: &'a RouteManifest,
    app_dir: &'a str,
    names: Names,
    imports: Imports,
    wrappers: Vec<String>,
    routes: Vec<String>,
    slots: BTreeMap<String, Vec<String>>,
}

impl TreeGen<'_> {
    /// Emits the wrapper component rendering a layout with `<Outlet/>` as `children`.
    fn layout_wrapper(&mut self, file: &str, base: &str) -> String {
        let component = self
            .imports
            .component(&mut self.names, "Layout", base, file);
        let wrapper = self.names.unique(&format!("{component}_Route"));
        let mut props = vec![String::from("children: createElement(Outlet)")];
        for slot in self.slots.get(file).cloned().unwrap_or_default() {
            let slot_files: Vec<String> = self
                .manifest
                .entries
                .iter()
                .filter(|e| e.slot.as_deref() == Some(slot.as_str()))
                .map(|e| e.file.clone())
                .collect();
            props.push(format!(
                "{slot}: null /* TODO(yolo-next): parallel slot @{slot} ({}) */",
                if slot_files.is_empty() {
                    String::from("no page")
                } else {
                    slot_files.join(", ")
                }
            ));
        }
        self.wrappers.push(format!(
            "function {wrapper}(): ReactElement {{\n  return createElement({component}, {{ {} }});\n}}",
            props.join(", ")
        ));
        wrapper
    }

    /// Emits the wrapper component passing `params` / `searchParams` promises to a page.
    fn page_wrapper(&mut self, page: &RouteEntry, route_var: &str, base: &str) -> String {
        let component = self
            .imports
            .component(&mut self.names, "Page", base, &page.file);
        let wrapper = self.names.unique(&format!("{component}_Route"));
        let params: Vec<String> = page
            .params
            .iter()
            .map(|p| {
                if p.catch_all {
                    format!(
                        "{}: (params._splat ?? \"\").split(\"/\").filter(Boolean)",
                        js_key(&p.name)
                    )
                } else {
                    format!("{}: params.{} ?? \"\"", js_key(&p.name), p.name)
                }
            })
            .collect();
        self.wrappers.push(format!(
            "function {wrapper}(): ReactElement {{\n  const params = {route_var}.useParams() as Record<string, string | undefined>;\n  const searchParams = {route_var}.useSearch() as Record<string, string | string[] | undefined>;\n  return createElement({component}, {{\n    params: Promise.resolve({{ {} }}),\n    searchParams: Promise.resolve(searchParams),\n  }});\n}}",
            params.join(", ")
        ));
        wrapper
    }

    /// Optional `pendingComponent` / `errorComponent` / `notFoundComponent` props.
    fn boundary_props(
        &mut self,
        base: &str,
        loading: Option<&str>,
        error: Option<&str>,
        not_found: Option<&str>,
    ) -> Vec<String> {
        let mut props = Vec::new();
        if let Some(file) = loading {
            let ident = self
                .imports
                .component(&mut self.names, "Loading", base, file);
            props.push(format!("pendingComponent: {ident}"));
        }
        if let Some(file) = error {
            let ident = self
                .imports
                .component(&mut self.names, "ErrorBoundary", base, file);
            props.push(format!("errorComponent: {ident}"));
        }
        if let Some(file) = not_found {
            let ident = self
                .imports
                .component(&mut self.names, "NotFound", base, file);
            props.push(format!("notFoundComponent: {ident}"));
        }
        props
    }

    /// Emits a layout node and its descendants; returns the expression to place in the parent's
    /// `addChildren` list.
    fn emit_node(
        &mut self,
        node: &LayoutNode<'_>,
        parent_var: &str,
        parent_prefix: &str,
    ) -> String {
        let (var, prefix) = match node.file {
            Some(file) if node.var.is_empty() => {
                let base = ident_from_file(self.app_dir, file);
                let var = self.names.unique(&format!("layout_{base}"));
                let wrapper = self.layout_wrapper(file, &base);
                let relative = relative_path(&node.tanstack_prefix, parent_prefix);
                let mut props = vec![format!("getParentRoute: () => {parent_var}")];
                if node.tanstack_prefix == parent_prefix {
                    props.push(format!("id: {}", js_str(&base.to_lowercase())));
                } else {
                    props.push(format!("path: {}", js_str(&relative)));
                }
                props.push(format!("component: {wrapper}"));
                self.routes.push(format!(
                    "const {var} = createRoute({{\n  {},\n}});",
                    props.join(",\n  ")
                ));
                (var, node.tanstack_prefix.clone())
            }
            _ => (node.var.clone(), node.tanstack_prefix.clone()),
        };
        let mut children = Vec::new();
        for item in &node.items {
            match item {
                TreeItem::Page(page) => children.push(self.emit_page(page, &var, &prefix)),
                TreeItem::Layout(child) => children.push(self.emit_node(child, &var, &prefix)),
            }
        }
        if node.var == "rootRoute" {
            return children.join(",\n  ");
        }
        if children.is_empty() {
            var
        } else {
            format!("{var}.addChildren([\n  {}\n])", children.join(",\n  "))
        }
    }

    /// Emits one page route; returns its variable name.
    fn emit_page(&mut self, page: &RouteEntry, parent_var: &str, parent_prefix: &str) -> String {
        let base = ident_from_url(&page.url_pattern);
        let var = self.names.unique(&format!("route_{base}"));
        let wrapper = self.page_wrapper(page, &var, &base);
        let mut props = vec![
            format!("getParentRoute: () => {parent_var}"),
            format!(
                "path: {}",
                js_str(&relative_path(&page.tanstack_path, parent_prefix))
            ),
            format!("component: {wrapper}"),
        ];
        props.extend(self.boundary_props(
            &base,
            page.loading.as_deref(),
            page.error.as_deref(),
            page.not_found.as_deref(),
        ));
        let comment = if page.legacy_pages {
            format!("// Pages Router `{}` ({})", page.file, page.url_pattern)
        } else {
            format!("// `{}` -> {}", page.file, page.url_pattern)
        };
        self.routes.push(format!(
            "{comment}\nconst {var} = createRoute({{\n  {},\n}});",
            props.join(",\n  ")
        ));
        var
    }
}

/// Quotes a JavaScript object key when it is not an identifier.
fn js_key(name: &str) -> String {
    let is_ident = !name.is_empty()
        && !name.starts_with(|c: char| c.is_ascii_digit())
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if is_ident {
        name.to_owned()
    } else {
        js_str(name)
    }
}

/// Generates `src/routeTree.gen.ts` (code-based `TanStack` Router tree).
// Linear template of the generated file; splitting would scatter its layout.
#[allow(clippy::too_many_lines)]
fn route_tree_ts(analysis: &ProjectAnalysis) -> String {
    let manifest = &analysis.routes;
    let app_dir = manifest.app_dir.as_deref().unwrap_or("app");
    let mut generator = TreeGen {
        manifest,
        app_dir,
        names: Names::default(),
        imports: Imports::default(),
        wrappers: Vec::new(),
        routes: Vec::new(),
        slots: layout_slots(manifest),
    };
    for reserved in [
        "rootRoute",
        "routeTree",
        "router",
        "createElement",
        "Outlet",
    ] {
        generator.names.used.insert(reserved.to_owned());
    }

    let mut root_props = Vec::new();
    if let Some(layout) = manifest.root_layout.as_deref() {
        let wrapper = generator.layout_wrapper(layout, "Root");
        root_props.push(format!("component: {wrapper}"));
    } else {
        root_props.push(String::from("component: Outlet"));
    }
    let root_error = manifest.global_error.as_deref().or_else(|| {
        manifest
            .tree
            .as_ref()
            .and_then(|t| t.files.error.as_deref())
    });
    let root_loading = manifest
        .tree
        .as_ref()
        .and_then(|t| t.files.loading.as_deref());
    root_props.extend(generator.boundary_props(
        "Root",
        root_loading,
        root_error,
        manifest.root_not_found.as_deref(),
    ));

    let tree = build_tree(manifest, app_dir);
    let children = generator.emit_node(&tree, "rootRoute", "");

    let handlers: Vec<String> = manifest
        .entries
        .iter()
        .filter(|e| e.kind != RouteKind::Page)
        .map(|e| {
            format!(
                "//   {:<10} {} ({})",
                format!("{:?}", e.kind),
                e.url_pattern,
                e.file
            )
        })
        .collect();
    let slotted: Vec<String> = manifest
        .entries
        .iter()
        .filter(|e| e.slot.is_some())
        .map(|e| {
            format!(
                "//   @{} {} ({})",
                e.slot.clone().unwrap_or_default(),
                e.url_pattern,
                e.file
            )
        })
        .collect();

    let mut out = String::new();
    out.push_str("// Generated by yolo-next. Code-based TanStack Router tree (do not edit; re-run the migration).\n");
    out.push_str("/* eslint-disable */\n");
    out.push_str("import { createRootRoute, createRoute, createRouter, Outlet } from \"@tanstack/react-router\";\n");
    out.push_str("import { createElement, type ReactElement } from \"react\";\n");
    for line in &generator.imports.lines {
        out.push_str(line);
        out.push('\n');
    }
    if !handlers.is_empty() {
        out.push_str(
            "\n// Served by Bun.serve routes (see .yolo/route-manifest.json), not by the router:\n",
        );
        out.push_str(&handlers.join("\n"));
        out.push('\n');
    }
    if !slotted.is_empty() {
        out.push_str(
            "\n// Parallel / intercepting entries rendered by their layout, not routed:\n",
        );
        out.push_str(&slotted.join("\n"));
        out.push('\n');
    }
    out.push('\n');
    out.push_str(&generator.wrappers.join("\n\n"));
    out.push_str("\n\nexport const rootRoute = createRootRoute({\n  ");
    out.push_str(&root_props.join(",\n  "));
    out.push_str(",\n});\n\n");
    out.push_str(&generator.routes.join("\n\n"));
    out.push_str("\n\nexport const routeTree = rootRoute.addChildren([\n  ");
    out.push_str(&children);
    out.push_str("\n]);\n\n");
    out.push_str(
        "export const router = createRouter({ routeTree, defaultPreload: \"intent\" });\n\n",
    );
    out.push_str("declare module \"@tanstack/react-router\" {\n  interface Register {\n    router: typeof router;\n  }\n}\n");
    out
}

