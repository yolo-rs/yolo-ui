fn fonts_css(analysis: &ProjectAnalysis) -> String {
    let mut css =
        String::from("/* Generated by yolo-next: self-hosted next/font replacements. */\n");
    for plan in &analysis.font_plans {
        css.push_str(&plan.css);
        if !plan.css.ends_with('\n') {
            css.push('\n');
        }
    }
    css
}

fn fonts_ts(analysis: &ProjectAnalysis) -> String {
    let mut names = Names::default();
    let mut out = String::from(
        "// Generated by yolo-next: next/font/google and next/font/local replacements.\n// Each export satisfies NextFont / NextFontWithVariable (className, variable, style).\nimport { yoloFont } from \"@yolo-rs/next/fonts\";\nimport \"./fonts.css\";\n\n",
    );
    for plan in &analysis.font_plans {
        let binding = names.unique(&js_identifier(&plan.request.binding));
        let family = match &plan.request.source {
            crate::types::FontSource::Google { family } => family.clone(),
            crate::types::FontSource::Local { .. } => String::from("local font"),
        };
        let _ = writeln!(
            out,
            "/** `{}` from `{}` ({family}). */\nexport const {binding} = yoloFont({{\n  className: {},",
            plan.request.import_name,
            plan.request.file,
            js_str(&plan.class_name)
        );
        if let Some(variable) = &plan.variable_class {
            let _ = writeln!(out, "  variable: {},", js_str(variable));
        }
        let _ = write!(
            out,
            "  style: {{ fontFamily: {} }},\n}});\n\n",
            js_str(&plan.family_css)
        );
    }
    out
}

/// Sanitizes a binding into a JavaScript identifier.
fn js_identifier(name: &str) -> String {
    let mut out: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' || c == '$' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if out.is_empty() || out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

/// `${env:NAME}` markers found in the serialized configs.
fn env_markers(analysis: &ProjectAnalysis) -> BTreeSet<String> {
    let mut keys = BTreeSet::new();
    let texts = [
        serde_json::to_string(&analysis.yolo_config).unwrap_or_default(),
        serde_json::to_string(&analysis.config).unwrap_or_default(),
    ];
    for text in &texts {
        let mut rest = text.as_str();
        while let Some(start) = rest.find("${env:") {
            let after = &rest[start + 6..];
            match after.find('}') {
                Some(end) => {
                    let key = &after[..end];
                    if !key.is_empty() && key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
                    {
                        keys.insert(key.to_owned());
                    }
                    rest = &after[end + 1..];
                }
                None => break,
            }
        }
    }
    keys
}

fn env_example(analysis: &ProjectAnalysis) -> String {
    let mut out = String::from("# Generated by yolo-next. Copy to .env and fill in the values.\n");
    out.push_str("# Variables prefixed with YOLO_PUBLIC_ (and the legacy NEXT_PUBLIC_) are inlined into client bundles.\n");
    if !analysis.yolo_config.public_env_prefixes.is_empty() {
        let _ = writeln!(
            out,
            "# Public prefixes: {}",
            analysis.yolo_config.public_env_prefixes.join(", ")
        );
    }
    out.push_str("PORT=3000\n");
    for key in env_markers(analysis) {
        let _ = writeln!(out, "{key}=");
    }
    for key in analysis.yolo_config.env.keys() {
        let _ = writeln!(out, "# {key} is inlined at build time from yolo.config.ts");
    }
    out
}

fn readme(analysis: &ProjectAnalysis) -> String {
    let (pages, handlers, metadata) = crate::project::route_counts(analysis);
    let mut out = format!(
        "# {}\n\nMigrated from Next.js {} to Bun 1.4.4 + `@yolo-rs/next` (React 19, TanStack Router) by yolo-next.\n\n",
        analysis.name,
        analysis.next_version.as_deref().unwrap_or("16")
    );
    out.push_str("## Run\n\n```sh\nbun install\nbun run dev      # Bun.serve with --hot reload\nbun run build    # production build into .yolo/\nbun run start    # serve the build\nbun run export   # static HTML export\n```\n\n");
    let _ = writeln!(
        out,
        "## Layout\n\n- `yolo.config.ts`: normalized configuration (was `next.config.*`).\n- `src/server.ts`: `createYoloNextApp` entry; `src/routeTree.gen.ts`: TanStack route tree ({pages} pages).\n- `.yolo/route-manifest.json`: {handlers} route handlers and {metadata} metadata routes served by `Bun.serve`.\n- `bunfig.toml` / `yolo.bundler.ts`: Turbopack rules and aliases translated to Bun plugins."
    );
    if !analysis.font_plans.is_empty() {
        out.push_str(
            "- `src/fonts.ts` / `src/fonts.css`: self-hosted replacements of `next/font`.\n",
        );
    }
    if analysis.proxy.is_some() {
        out.push_str(
            "- `src/proxy.ts`: `proxy.ts` / `middleware.ts` translated to a Bun fetch hook.\n",
        );
    }
    out.push_str("\nThe original `next`, `eslint-config-next` and `@next/*` dependencies were removed from `package.json`; the remaining dependencies were carried over. See `MIGRATION-REPORT.md` for the feature parity table and diagnostics.\n");
    out
}

