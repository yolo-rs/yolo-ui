//! Qt 6 / QML / cxx-qt adapter for Yolo UI and Material Design 3:
//! - [`palette::QPaletteTable`] and [`palette::palette_for_preset`] provide a 21-role
//!   `QPalette::ColorRole` mapping for any [`DynamicScheme`] or any of the 5 [`YoloThemePreset`]s
//!   (`Neutral`, `M3`, `Fluent`, `Apple`, `Aphrody`);
//! - [`qml_singleton`] and [`qml_singleton_for_preset`] generate `YoloTheme.qml` / `M3Theme.qml`
//!   Qt Quick singletons for all 5 presets;
//! - [`scheme::YoloQtScheme`] and [`scheme::CxxQtBridgeDescriptor`] provide pure-Rust QML property
//!   and invokable descriptors without requiring system `qmake`.

use std::fmt::Write;
use yolo_emit::{ROLES, Target, Theme, emit, hex};
pub use yolo_shared::{
    BYRON_LOVE_PALETTE, BYRON_LOVE_PET_SPEC, ByronLoveColorTeinte, ByronLovePetSpec, YoloManifest,
    YoloStyle, YoloThemePreset, YoloThemeTokens,
};
use yolo_tokens::presets::{scheme_for_preset, variant_for_preset};
pub use yolo_tokens::role::Role;
pub use yolo_tokens::scheme::{DynamicScheme, Variant};

pub mod palette;
pub mod scheme;

/// Generates a standalone `M3Theme.qml` singleton (`pragma Singleton; import QtQuick; QtObject { ... }`)
/// for `(seed, variant, contrast)` when a project wants a pure-QML file in its resource tree.
#[must_use]
pub fn qml_singleton(seed: u32, variant: Variant, contrast: f64) -> String {
    emit(
        &Theme {
            seed,
            variant,
            contrast,
        },
        Target::Qml,
    )
}

/// Generates a standalone `YoloTheme.qml` singleton for one of the 5 [`YoloThemePreset`]s
/// (`Neutral`, `M3`, `Fluent`, `Apple`, `Aphrody`), including both light and dark tokens and
/// preset shape radii (`radiusSmall`, `radiusMedium`, `radiusLarge`).
#[must_use]
pub fn qml_singleton_for_preset(preset: YoloThemePreset) -> String {
    let light = scheme_for_preset(preset, false);
    let dark = scheme_for_preset(preset, true);
    let light_tokens = preset.tokens(false);
    let dark_tokens = preset.tokens(true);
    let (r_sm, r_md, r_lg) = match preset {
        YoloThemePreset::Omarchy => (0, 2, 4),
        YoloThemePreset::Fluent => (4, 8, 12),
        YoloThemePreset::Apple => (10, 14, 18),
        YoloThemePreset::Hyprland => (10, 12, 16),
        YoloThemePreset::Neutral => (8, 12, 16),
        YoloThemePreset::M3 | YoloThemePreset::Aphrody => (8, 12, 16),
        YoloThemePreset::Chromium => (4, 8, 12),
    };

    let mut out = String::from(
        "// Generated by yolo-qt (YoloTheme.qml). Do not hand-edit.\npragma Singleton\nimport QtQuick\n\nQtObject {\n",
    );
    let _ = writeln!(
        out,
        "    readonly property string presetId: \"{}\"",
        preset.id()
    );
    let _ = writeln!(
        out,
        "    readonly property string presetName: \"{}\"",
        preset.display_name()
    );
    out.push_str(
        "    property bool dark: Application.styleHints.colorScheme === Qt.ColorScheme.Dark\n",
    );
    let _ = writeln!(out, "    readonly property int radiusSmall: {r_sm}");
    let _ = writeln!(out, "    readonly property int radiusMedium: {r_md}");
    let _ = writeln!(out, "    readonly property int radiusLarge: {r_lg}");

    for &role in ROLES {
        let (d_hex, l_hex) = match role {
            Role::Primary => (
                dark_tokens.accent_primary.to_owned(),
                light_tokens.accent_primary.to_owned(),
            ),
            Role::Secondary => (
                dark_tokens.accent_secondary.to_owned(),
                light_tokens.accent_secondary.to_owned(),
            ),
            Role::Surface => (
                dark_tokens.bg_primary.to_owned(),
                light_tokens.bg_primary.to_owned(),
            ),
            Role::SurfaceContainer => (
                dark_tokens.bg_surface.to_owned(),
                light_tokens.bg_surface.to_owned(),
            ),
            Role::SurfaceContainerHigh => (
                dark_tokens.bg_elevated.to_owned(),
                light_tokens.bg_elevated.to_owned(),
            ),
            Role::OnSurface => (
                dark_tokens.text_primary.to_owned(),
                light_tokens.text_primary.to_owned(),
            ),
            Role::OnSurfaceVariant => (
                dark_tokens.text_secondary.to_owned(),
                light_tokens.text_secondary.to_owned(),
            ),
            _ => (hex(dark.argb(role)), hex(light.argb(role))),
        };
        let _ = writeln!(
            out,
            "    readonly property color {}: dark ? \"{}\" : \"{}\"",
            role.camel_name(),
            d_hex,
            l_hex
        );
    }
    out.push_str("}\n");
    out
}

/// Conventional QML singleton file name for Yolo UI (`YoloTheme.qml`).
pub const YOLO_THEME_QML_FILENAME: &str = "YoloTheme.qml";

/// Returns the canonical M3 [`Variant`] for a [`YoloThemePreset`].
#[must_use]
pub const fn preset_variant(preset: YoloThemePreset) -> Variant {
    variant_for_preset(preset)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn palette_covers_all_21_qpalette_roles() {
        let s = DynamicScheme::from_argb(0xFF67_50A4, Variant::TonalSpot, true, 0.0);
        let p = palette::palette_argb(&s);
        assert_eq!(p.len(), 21);
        for &(name, _, argb) in &p {
            assert!(!name.is_empty());
            assert_eq!(argb >> 24, 0xFF);
        }
    }

    #[test]
    fn qml_singleton_declares_all_roles() {
        let qml = qml_singleton(0xFF67_50A4, Variant::TonalSpot, 0.0);
        assert!(qml.contains("pragma Singleton"));
        assert!(qml.contains("readonly property color primary:"));
        assert!(qml.contains("readonly property color surfaceContainerHigh:"));
    }

    #[test]
    fn all_five_presets_generate_yolo_theme_qml_and_qpalette_tables() {
        for preset in YoloThemePreset::ALL {
            let qml = qml_singleton_for_preset(preset);
            assert!(qml.contains("pragma Singleton"));
            assert!(qml.contains(preset.id()));
            assert!(qml.contains("readonly property int radiusSmall:"));
            assert!(qml.contains("readonly property color primary:"));

            let table = palette::QPaletteTable::from_preset(preset, true);
            assert_eq!(table.entries.len(), 21);
            assert!(table.role_argb("Accent").is_some());
            let cpp = table.to_cpp_function("applyYoloPalette");
            assert!(cpp.contains("QPalette::Accent"));

            let bridge_scheme = scheme::YoloQtScheme::for_preset(preset, true);
            assert_eq!(bridge_scheme.preset, Some(preset));
            assert!(!bridge_scheme.role_hex("primary").is_empty());
            assert!(!bridge_scheme.qpalette_hex("Window").is_empty());
        }

        // Check CxxQt bridge descriptor
        let desc = scheme::CxxQtBridgeDescriptor::CANONICAL;
        assert_eq!(desc.qml_uri, "com.yolo.ui");
        assert_eq!(desc.qobject_name, "M3Scheme");
        assert_eq!(desc.properties.len(), 40);
        assert_eq!(desc.invokables.len(), 3);
    }
}
