//! Omarchy theme directories.
//!
//! An Omarchy theme (`~/.config/omarchy/themes/<name>/`) is driven by `colors.toml`: Omarchy's
//! `omarchy-theme-set-templates` renders Alacritty, Ghostty, Kitty, Foot, btop, Hyprland,
//! Chromium, Helix, Neovim and the other `default/themed/*.tpl` configs from it, and
//! `icons.theme` names the Yaru icon variant. Each theme source yields a dark directory
//! (`<slug>`) and a light one (`<slug>-light`) with the canonical `colors.toml` keys of
//! `bin/omarchy-theme-color` plus `hyprland_active_border` / `hyprland_inactive_border`
//! gradients. Wallpapers (`backgrounds/`) and previews are owner assets and are not generated.

use crate::extended::{neutral, neutral_variant, terminal};
use crate::{EmittedFile, ThemeSource, c, hex};
use std::fmt::Write;
use yolo_shared::{HYPRLAND_DECORATION_SPEC, OmarchySubTheme, YoloThemePreset};
use yolo_tokens::hct::Hct;
use yolo_tokens::role::Role;

