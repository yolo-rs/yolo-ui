//! Theme for the DioxusLabs component library (`dioxus-components`, 45 styled components).
//!
//! The library reads `--primary-color-*`, `--secondary-color-*`, status and focus variables from
//! `dx-components-theme.css`, each written as `var(--dark, <dark>) var(--light, <light>)` so one
//! declaration serves both schemes. This module writes that same file for any
//! [`YoloThemePreset`], with every colour taken from the preset seed through the HCT tonal
//! palettes of `yolo-tokens`, so the upstream components follow our presets.

use std::fmt::Write as _;

use yolo_shared::YoloThemePreset;
use yolo_tokens::palette::{CorePalette, TonalPalette};

/// One variable: its name and the tone used in the dark and light schemes.
struct Tones {
    name: &'static str,
    dark: f64,
    light: f64,
}

const fn tones(name: &'static str, dark: f64, light: f64) -> Tones {
    Tones { name, dark, light }
}

/// Surfaces, from the page background up: the neutral palette, near black in dark, near white in light.
const SURFACES: [Tones; 8] = [
    tones("--primary-color", 0.0, 100.0),
    tones("--primary-color-1", 5.0, 99.0),
    tones("--primary-color-2", 3.0, 100.0),
    tones("--primary-color-3", 7.0, 98.0),
    tones("--primary-color-4", 10.0, 98.0),
    tones("--primary-color-5", 15.0, 96.0),
    tones("--primary-color-6", 14.0, 91.0),
    tones("--primary-color-7", 25.0, 72.0),
];

/// Foregrounds, from strongest to faintest.
const FOREGROUNDS: [Tones; 7] = [
    tones("--secondary-color", 100.0, 0.0),
    tones("--secondary-color-1", 98.0, 0.0),
    tones("--secondary-color-2", 91.0, 5.0),
    tones("--secondary-color-3", 87.0, 17.0),
    tones("--secondary-color-4", 84.0, 7.0),
    tones("--secondary-color-5", 65.0, 55.0),
    tones("--secondary-color-6", 38.0, 83.0),
];

fn hex(argb: u32) -> String {
    format!("#{:06x}", argb & 0x00FF_FFFF)
}

fn line(out: &mut String, name: &str, palette: &TonalPalette, dark: f64, light: f64) {
    let _ = writeln!(
        out,
        "  {name}: var(--dark, {}) var(--light, {});",
        hex(palette.tone(dark)),
        hex(palette.tone(light))
    );
}

/// `dx-components-theme.css` for `preset`: scheme switches, then every variable the components read.
#[must_use]
pub fn emit_dioxus_components_theme(preset: YoloThemePreset) -> String {
    let core = CorePalette::of(preset.seed_argb());
    // Status hues are fixed so success, warning and error keep their meaning in every preset.
    let success = TonalPalette::from_hue_and_chroma(145.0, 48.0);
    let warning = TonalPalette::from_hue_and_chroma(75.0, 60.0);

    let mut out = format!(
        "/* dx-components-theme.css for {} ({}), generated by yolo-emit from seed {}. */\n\n",
        preset.id(),
        preset.display_name(),
        preset.seed_hex()
    );
    out.push_str(SCHEME_SWITCHES);
    out.push_str(":root {\n");
    for t in &SURFACES {
        line(&mut out, t.name, &core.n1, t.dark, t.light);
    }
    for t in &FOREGROUNDS {
        line(&mut out, t.name, &core.n1, t.dark, t.light);
    }
    line(&mut out, "--focused-border-color", &core.a1, 70.0, 50.0);
    line(&mut out, "--primary-success-color", &success, 15.0, 97.0);
    line(&mut out, "--secondary-success-color", &success, 85.0, 50.0);
    line(&mut out, "--primary-warning-color", &warning, 15.0, 97.0);
    line(&mut out, "--secondary-warning-color", &warning, 88.0, 65.0);
    line(&mut out, "--primary-error-color", &core.error, 40.0, 50.0);
    line(&mut out, "--secondary-error-color", &core.error, 35.0, 60.0);
    out.push_str(
        "  --contrast-error-color: var(--dark, var(--secondary-color-3)) var(--light, var(--primary-color));\n\
         \x20 --primary-info-color: var(--dark, var(--primary-color-5)) var(--light, var(--primary-color));\n\
         \x20 --secondary-info-color: var(--dark, var(--primary-color-7)) var(--light, var(--secondary-color-3));\n}\n",
    );
    out
}

/// Scheme switches copied in behaviour from upstream: `data-theme` wins, else the OS preference.
const SCHEME_SWITCHES: &str = "html[data-theme=\"dark\"] {\n  --dark: initial;\n  --light: ;\n}\n\n\
html[data-theme=\"light\"] {\n  --dark: ;\n  --light: initial;\n}\n\n\
html[data-theme=\"dark\"] [class~=\"dxc-system\"] {\n  --dxc-light-on: ;\n  --dxc-dark-on: initial;\n}\n\n\
html[data-theme=\"light\"] [class~=\"dxc-system\"] {\n  --dxc-light-on: initial;\n  --dxc-dark-on: ;\n}\n\n\
@media (prefers-color-scheme: dark) {\n  :root {\n    --dark: initial;\n    --light: ;\n  }\n}\n\n\
@media (prefers-color-scheme: light) {\n  :root {\n    --dark: ;\n    --light: initial;\n  }\n}\n\n";

#[cfg(test)]
mod tests {
    use super::*;

    /// Every variable upstream `dx-components-theme.css` declares in `:root`.
    const UPSTREAM_VARIABLES: [&str; 25] = [
        "--primary-color",
        "--primary-color-1",
        "--primary-color-2",
        "--primary-color-3",
        "--primary-color-4",
        "--primary-color-5",
        "--primary-color-6",
        "--primary-color-7",
        "--secondary-color",
        "--secondary-color-1",
        "--secondary-color-2",
        "--secondary-color-3",
        "--secondary-color-4",
        "--secondary-color-5",
        "--secondary-color-6",
        "--focused-border-color",
        "--primary-success-color",
        "--secondary-success-color",
        "--primary-warning-color",
        "--secondary-warning-color",
        "--primary-error-color",
        "--secondary-error-color",
        "--contrast-error-color",
        "--primary-info-color",
        "--secondary-info-color",
    ];

    #[test]
    fn declares_every_upstream_variable_for_every_preset() {
        for preset in YoloThemePreset::ALL {
            let css = emit_dioxus_components_theme(preset);
            for var in UPSTREAM_VARIABLES {
                assert!(
                    css.contains(&format!("  {var}: ")),
                    "{} lacks {var}",
                    preset.id()
                );
            }
            assert_eq!(
                css.matches('{').count(),
                css.matches('}').count(),
                "balanced braces"
            );
        }
    }

    #[test]
    fn presets_produce_different_focus_colours() {
        let focus = |p| {
            emit_dioxus_components_theme(p)
                .lines()
                .find(|l| l.contains("--focused-border-color"))
                .map(str::to_owned)
        };
        assert_ne!(focus(YoloThemePreset::M3), focus(YoloThemePreset::Fluent));
    }

    #[test]
    fn extreme_tones_are_pure_black_and_white() {
        let css = emit_dioxus_components_theme(YoloThemePreset::Neutral);
        assert!(css.contains("--primary-color: var(--dark, #000000) var(--light, #ffffff);"));
    }
}
