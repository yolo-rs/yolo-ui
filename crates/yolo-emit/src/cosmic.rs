//! COSMIC `ThemeBuilder` RON (`cosmic-theme`, config version 2).
//!
//! Each file is one `ThemeBuilder` value, the format COSMIC Settings > Appearance imports and
//! exports, with a complete `CosmicPalette` (neutral ramp, accent hues, extended hues) derived
//! from the scheme's palettes and the builder overrides (background, containers, text tint,
//! accent, success, warning, destructive) set to Material roles. Spacing and corner radii follow
//! the preset's `YoloStyle` grid.

use crate::extended::{harmonized_palette, neutral, status, terminal};
use crate::{EmittedFile, ThemeSource, quoted, rgb};
use std::fmt::Write;
use yolo_tokens::role::Role;
use yolo_tokens::scheme::DynamicScheme;

fn rgba(argb: u32) -> String {
    let (r, g, b) = rgb(argb);
    format!(
        "(red: {:.6}, green: {:.6}, blue: {:.6}, alpha: 1.0)",
        f32::from(r) / 255.0,
        f32::from(g) / 255.0,
        f32::from(b) / 255.0
    )
}

fn srgb(argb: u32) -> String {
    let (r, g, b) = rgb(argb);
    format!(
        "(red: {:.6}, green: {:.6}, blue: {:.6})",
        f32::from(r) / 255.0,
        f32::from(g) / 255.0,
        f32::from(b) / 255.0
    )
}

/// Accent and extended hues of the COSMIC palette (HCT hue, harmonized toward the seed).
const ACCENT_HUES: [(&str, f64); 9] = [
    ("accent_blue", 220.0),
    ("accent_indigo", 265.0),
    ("accent_purple", 300.0),
    ("accent_pink", 350.0),
    ("accent_red", 25.0),
    ("accent_orange", 60.0),
    ("accent_yellow", 95.0),
    ("accent_green", 145.0),
    ("accent_warm_grey", 50.0),
];
const EXT_HUES: [(&str, f64); 7] = [
    ("ext_warm_grey", 50.0),
    ("ext_orange", 60.0),
    ("ext_yellow", 95.0),
    ("ext_blue", 220.0),
    ("ext_purple", 300.0),
    ("ext_pink", 350.0),
    ("ext_indigo", 265.0),
];

fn palette(out: &mut String, src: &ThemeSource, s: &DynamicScheme) {
    let dark = s.is_dark;
    let seed = src.theme.seed;
    let term = terminal(s);
    let variant = if dark { "Dark" } else { "Light" };
    let _ = write!(
        out,
        "    palette: {variant}((\n        name: {},\n",
        quoted(&format!("{}-{}", src.slug, variant.to_ascii_lowercase()))
    );
    let mut field = |name: &str, argb: u32| {
        let _ = writeln!(out, "        {name}: {},", rgba(argb));
    };
    field("bright_red", term.bright_red);
    field("bright_green", term.bright_green);
    field(
        "bright_orange",
        harmonized_palette(seed, 55.0, 56.0).tone(if dark { 80.0 } else { 30.0 }),
    );
    field("gray_1", neutral(s, if dark { 10.0 } else { 86.0 }));
    field("gray_2", neutral(s, if dark { 15.0 } else { 90.0 }));
    for i in 0..=10u8 {
        let tone = f64::from(i) * 10.0;
        let tone = if dark { tone } else { 100.0 - tone };
        field(&format!("neutral_{i}"), neutral(s, tone));
    }
    for (name, hue) in ACCENT_HUES {
        let chroma = if name.ends_with("grey") { 12.0 } else { 48.0 };
        field(
            name,
            harmonized_palette(seed, hue, chroma).tone(if dark { 75.0 } else { 35.0 }),
        );
    }
    for (name, hue) in EXT_HUES {
        let chroma = if name.ends_with("grey") { 12.0 } else { 64.0 };
        field(
            name,
            harmonized_palette(seed, hue, chroma).tone(if dark { 65.0 } else { 45.0 }),
        );
    }
    out.push_str("    )),\n");
}

/// One `ThemeBuilder`.
#[must_use]
pub fn theme_builder(src: &ThemeSource, dark: bool) -> String {
    let s = src.scheme(dark);
    let status = status(s);
    let mut out = format!(
        "// Generated by yolo-emit for {} ({}) from yolo-tokens roles. Import in COSMIC Settings > Appearance.\n(\n",
        src.name,
        if dark { "dark" } else { "light" }
    );
    palette(&mut out, src, s);
    let grid = src.style().map_or(4.0, |st| st.spacing_grid_px).max(1.0);
    let steps: [(&str, f32); 10] = [
        ("space_none", 0.0),
        ("space_xxxs", 1.0),
        ("space_xxs", 2.0),
        ("space_xs", 3.0),
        ("space_s", 4.0),
        ("space_m", 6.0),
        ("space_l", 8.0),
        ("space_xl", 12.0),
        ("space_xxl", 16.0),
        ("space_xxxl", 32.0),
    ];
    out.push_str("    spacing: (\n");
    for (name, k) in steps {
        let _ = writeln!(out, "        {name}: {},", (k * grid).round() as u16);
    }
    out.push_str("    ),\n");
    let (sm, md, lg) = src.style().map_or((4.0, 8.0, 12.0), |st| {
        (st.radius_sm_px, st.radius_md_px, st.radius_lg_px)
    });
    let radii: [(&str, f32); 6] = [
        ("radius_0", 0.0),
        ("radius_xs", (sm / 2.0).round()),
        ("radius_s", sm),
        ("radius_m", md),
        ("radius_l", lg),
        ("radius_xl", (lg * 1.5).min(160.0)),
    ];
    out.push_str("    corner_radii: (\n");
    for (name, r) in radii {
        let _ = writeln!(out, "        {name}: ({r:.1}, {r:.1}, {r:.1}, {r:.1}),");
    }
    out.push_str("    ),\n");
    let fields: [(&str, String); 10] = [
        ("neutral_tint", srgb(s.palettes.neutral.key_color.to_argb())),
        ("bg_color", rgba(s.argb(Role::Surface))),
        ("primary_container_bg", rgba(s.argb(Role::SurfaceContainer))),
        (
            "secondary_container_bg",
            rgba(s.argb(Role::SurfaceContainerHigh)),
        ),
        ("text_tint", srgb(s.argb(Role::OnSurface))),
        ("accent", srgb(s.argb(Role::Primary))),
        ("success", srgb(status.success.color)),
        ("warning", srgb(status.warning.color)),
        ("destructive", srgb(s.argb(Role::Error))),
        ("window_hint", srgb(s.argb(Role::Primary))),
    ];
    for (name, value) in &fields[..9] {
        let _ = writeln!(out, "    {name}: Some({value}),");
    }
    let gaps = src
        .style()
        .map_or(8.0, |st| st.spacing_grid_px * 2.0)
        .round() as u32;
    let _ = writeln!(
        out,
        "    is_frosted: false,\n    gaps: (0, {gaps}),\n    active_hint: 3,\n    {}: Some({}),\n)",
        fields[9].0, fields[9].1
    );
    out
}

/// `<slug>-dark.ron` then `<slug>-light.ron`.
#[must_use]
pub fn files(src: &ThemeSource) -> Vec<EmittedFile> {
    vec![
        EmittedFile::new(format!("{}-dark.ron", src.slug), theme_builder(src, true)),
        EmittedFile::new(format!("{}-light.ron", src.slug), theme_builder(src, false)),
    ]
}
