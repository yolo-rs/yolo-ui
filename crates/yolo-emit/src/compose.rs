//! Jetpack Compose Material 3 theme (`androidx.compose.material3`).
//!
//! `<Pascal>Theme.kt` declares `<Pascal>LightColorScheme` / `<Pascal>DarkColorScheme` through
//! `lightColorScheme(...)` / `darkColorScheme(...)` with every Material 3 role parameter, and a
//! `<Pascal>Theme` composable that prefers Android 12+ dynamic color (Material You) when
//! `dynamicColor` is true and falls back to the generated schemes.

use crate::{EmittedFile, ThemeSource, rgb};
use std::fmt::Write;
use yolo_tokens::role::Role;
use yolo_tokens::scheme::DynamicScheme;

/// Kotlin package of the generated file.
pub const PACKAGE: &str = "rs.yolo.ui.theme";

/// `lightColorScheme` / `darkColorScheme` parameters (Compose Material 3 1.2+), in declaration order.
pub const PARAMS: &[Role] = &[
    Role::Primary,
    Role::OnPrimary,
    Role::PrimaryContainer,
    Role::OnPrimaryContainer,
    Role::InversePrimary,
    Role::Secondary,
    Role::OnSecondary,
    Role::SecondaryContainer,
    Role::OnSecondaryContainer,
    Role::Tertiary,
    Role::OnTertiary,
    Role::TertiaryContainer,
    Role::OnTertiaryContainer,
    Role::Background,
    Role::OnBackground,
    Role::Surface,
    Role::OnSurface,
    Role::SurfaceVariant,
    Role::OnSurfaceVariant,
    Role::SurfaceTint,
    Role::InverseSurface,
    Role::InverseOnSurface,
    Role::Error,
    Role::OnError,
    Role::ErrorContainer,
    Role::OnErrorContainer,
    Role::Outline,
    Role::OutlineVariant,
    Role::Scrim,
    Role::SurfaceBright,
    Role::SurfaceContainer,
    Role::SurfaceContainerHigh,
    Role::SurfaceContainerHighest,
    Role::SurfaceContainerLow,
    Role::SurfaceContainerLowest,
    Role::SurfaceDim,
];

fn scheme_val(out: &mut String, name: &str, builder: &str, s: &DynamicScheme) {
    let _ = writeln!(out, "val {name}: ColorScheme = {builder}(");
    for &role in PARAMS {
        let (r, g, b) = rgb(s.argb(role));
        let _ = writeln!(
            out,
            "    {} = Color(0xFF{r:02X}{g:02X}{b:02X}),",
            role.camel_name()
        );
    }
    out.push_str(")\n\n");
}

/// The Kotlin source.
#[must_use]
pub fn theme_kt(src: &ThemeSource) -> String {
    let p = src.pascal();
    let mut out = format!(
        "// Generated by yolo-emit for {} from yolo-tokens roles. Do not hand-edit.\npackage {PACKAGE}\n\nimport android.os.Build\nimport androidx.compose.foundation.isSystemInDarkTheme\nimport androidx.compose.material3.ColorScheme\nimport androidx.compose.material3.MaterialTheme\nimport androidx.compose.material3.darkColorScheme\nimport androidx.compose.material3.dynamicDarkColorScheme\nimport androidx.compose.material3.dynamicLightColorScheme\nimport androidx.compose.material3.lightColorScheme\nimport androidx.compose.runtime.Composable\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.platform.LocalContext\n\n",
        src.name
    );
    scheme_val(
        &mut out,
        &format!("{p}LightColorScheme"),
        "lightColorScheme",
        &src.light,
    );
    scheme_val(
        &mut out,
        &format!("{p}DarkColorScheme"),
        "darkColorScheme",
        &src.dark,
    );
    let _ = write!(
        out,
        "/** {name}: dynamic color on Android 12+ when [dynamicColor], otherwise the generated schemes. */\n@Composable\nfun {p}Theme(\n    darkTheme: Boolean = isSystemInDarkTheme(),\n    dynamicColor: Boolean = false,\n    content: @Composable () -> Unit,\n) {{\n    val colorScheme = when {{\n        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {{\n            val context = LocalContext.current\n            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)\n        }}\n        darkTheme -> {p}DarkColorScheme\n        else -> {p}LightColorScheme\n    }}\n    MaterialTheme(colorScheme = colorScheme, content = content)\n}}\n",
        name = src.name
    );
    out
}

/// `<Pascal>Theme.kt`.
#[must_use]
pub fn files(src: &ThemeSource) -> Vec<EmittedFile> {
    vec![EmittedFile::new(
        format!("{}Theme.kt", src.pascal()),
        theme_kt(src),
    )]
}
