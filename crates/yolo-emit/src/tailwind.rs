//! Tailwind CSS v4 + shadcn/ui theme (`globals.css` variables).
//!
//! shadcn/ui themes through plain CSS custom properties (`--background`, `--primary`, ...) declared
//! on `:root` (light) and `.dark`; Tailwind v4 exposes them as utilities (`bg-background`) through an
//! `@theme inline { --color-background: var(--background); }` block. This module writes both for any
//! [`YoloThemePreset`], taking every colour from the HCT `DynamicScheme` of the preset (light and
//! dark resolved separately), written as hex.
//!
//! Source of the variable list: the shadcn/ui theming documentation (`--background` ...
//! `--sidebar-ring` plus `--radius`). Role choices are ours and are recorded in [`SHADCN_ROLE_MAP`];
//! `catalog/conversion.toml` has no section for this target, so the table lives here only.

use std::fmt::Write as _;

use crate::Theme;
use yolo_shared::YoloThemePreset;
use yolo_tokens::role::Role;
use yolo_tokens::scheme::DynamicScheme;

/// shadcn variable (without `--`) mapped to the HCT role that fills it, same role in light and dark.
///
/// Rationale: `card` and `sidebar` sit one surface step above `background`, `popover` two; `secondary`,
/// `accent` and `muted` use container roles so filled controls stay below `primary` in emphasis;
/// `border` is `outline-variant` and `input` is the stronger `outline`; `ring` is `primary`; `chart-*`
/// take five distinct accent roles.
pub const SHADCN_ROLE_MAP: &[(&str, Role)] = &[
    ("background", Role::Background),
    ("foreground", Role::OnBackground),
    ("card", Role::SurfaceContainerLow),
    ("card-foreground", Role::OnSurface),
    ("popover", Role::SurfaceContainer),
    ("popover-foreground", Role::OnSurface),
    ("primary", Role::Primary),
    ("primary-foreground", Role::OnPrimary),
    ("secondary", Role::SecondaryContainer),
    ("secondary-foreground", Role::OnSecondaryContainer),
    ("muted", Role::SurfaceContainerHigh),
    ("muted-foreground", Role::OnSurfaceVariant),
    ("accent", Role::TertiaryContainer),
    ("accent-foreground", Role::OnTertiaryContainer),
    ("destructive", Role::Error),
    ("destructive-foreground", Role::OnError),
    ("border", Role::OutlineVariant),
    ("input", Role::Outline),
    ("ring", Role::Primary),
    ("chart-1", Role::Primary),
    ("chart-2", Role::Tertiary),
    ("chart-3", Role::Secondary),
    ("chart-4", Role::InversePrimary),
    ("chart-5", Role::Error),
    ("sidebar", Role::SurfaceContainerLow),
    ("sidebar-foreground", Role::OnSurface),
    ("sidebar-primary", Role::Primary),
    ("sidebar-primary-foreground", Role::OnPrimary),
    ("sidebar-accent", Role::SecondaryContainer),
    ("sidebar-accent-foreground", Role::OnSecondaryContainer),
    ("sidebar-border", Role::OutlineVariant),
    ("sidebar-ring", Role::Primary),
];

fn hex(argb: u32) -> String {
    format!("#{:06x}", argb & 0x00FF_FFFF)
}

fn block(out: &mut String, selector: &str, scheme: &DynamicScheme, radius: f32) {
    let _ = writeln!(out, "{selector} {{");
    let _ = writeln!(out, "  --radius: {radius}px;");
    for (name, role) in SHADCN_ROLE_MAP {
        let _ = writeln!(out, "  --{name}: {};", hex(scheme.argb(*role)));
    }
    out.push_str("}\n\n");
}

/// `globals.css` for `preset`: `:root` (light), `.dark`, then the Tailwind v4 `@theme inline` bridge.
#[must_use]
pub fn emit_tailwind_theme(preset: YoloThemePreset) -> String {
    let theme = Theme::from_preset(preset);
    let radius = preset.style().radius_md_px;
    let mut out = format!(
        "/* shadcn/ui + Tailwind v4 theme for {} ({}), generated by yolo-emit from seed {}. */\n\n\
@custom-variant dark (&:is(.dark *));\n\n",
        preset.id(),
        preset.display_name(),
        preset.seed_hex()
    );
    block(&mut out, ":root", &theme.scheme(false), radius);
    block(&mut out, ".dark", &theme.scheme(true), radius);
    out.push_str("@theme inline {\n");
    for (name, _) in SHADCN_ROLE_MAP {
        let _ = writeln!(out, "  --color-{name}: var(--{name});");
    }
    out.push_str(
        "  --radius-sm: calc(var(--radius) - 4px);\n  --radius-md: calc(var(--radius) - 2px);\n  \
--radius-lg: var(--radius);\n  --radius-xl: calc(var(--radius) + 4px);\n}\n",
    );
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn declares_every_variable_in_every_mode_and_theme_bridge() {
        for preset in YoloThemePreset::ALL {
            let css = emit_tailwind_theme(preset);
            for (name, _) in SHADCN_ROLE_MAP {
                assert_eq!(
                    css.matches(&format!("  --{name}: #")).count(),
                    2,
                    "{} needs --{name} in light and dark",
                    preset.id()
                );
                assert!(css.contains(&format!("  --color-{name}: var(--{name});")));
            }
            assert!(css.contains("--radius: ") && css.contains("@theme inline {"));
            assert_eq!(css.matches('{').count(), css.matches('}').count(), "balanced braces");
        }
    }

    #[test]
    fn required_shadcn_names_are_present() {
        for need in [
            "background", "foreground", "card", "primary", "primary-foreground", "secondary",
            "muted", "accent", "destructive", "border", "input", "ring", "chart-1", "chart-5",
            "sidebar", "sidebar-ring",
        ] {
            assert!(SHADCN_ROLE_MAP.iter().any(|(n, _)| *n == need), "{need}");
        }
    }

    #[test]
    fn presets_differ_and_modes_differ() {
        let a = emit_tailwind_theme(YoloThemePreset::M3);
        assert_ne!(a, emit_tailwind_theme(YoloThemePreset::Fluent));
        let mut parts = a.split(".dark {");
        let light = parts.next().unwrap_or_default();
        let dark = parts.next().unwrap_or_default();
        let bg = |s: &str| s.lines().find(|l| l.contains("--background:")).map(str::to_owned);
        assert_ne!(bg(light), bg(dark));
    }
}
