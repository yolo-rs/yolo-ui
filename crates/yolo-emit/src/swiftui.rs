//! Xcode asset catalog colors plus a SwiftUI accessor file.
//!
//! `<Pascal>.xcassets/<Role>.colorset/Contents.json` carries four appearances per role: any
//! (light), `luminosity: dark`, `contrast: high`, and dark + high contrast. High-contrast
//! entries come from the same request resolved at contrast level 1.0, so "Increase Contrast"
//! on macOS and iOS selects a scheme that `yolo-tokens` solved for it. `<Pascal>Colors.swift`
//! exposes every color as `Color.<Pascal>.<role>` and names the matching `NSAppearance`s.

use crate::extended::status;
use crate::{EmittedFile, ThemeSource, rgb};
use std::fmt::Write;
use yolo_tokens::role::Role;
use yolo_tokens::scheme::DynamicScheme;

/// One named color in the catalog.
#[derive(Clone, Copy)]
enum Src {
    Role(Role),
    Success,
    OnSuccess,
    Warning,
    OnWarning,
}

fn entries() -> Vec<(String, String, Src)> {
    let mut out: Vec<(String, String, Src)> = Role::ALL
        .iter()
        .map(|&r| {
            (
                pascal_camel(r.camel_name()),
                r.camel_name().to_owned(),
                Src::Role(r),
            )
        })
        .collect();
    for (name, src) in [
        ("success", Src::Success),
        ("onSuccess", Src::OnSuccess),
        ("warning", Src::Warning),
        ("onWarning", Src::OnWarning),
    ] {
        out.push((pascal_camel(name), name.to_owned(), src));
    }
    out
}

fn pascal_camel(camel: &str) -> String {
    let mut chars = camel.chars();
    chars.next().map_or_else(String::new, |first| {
        first.to_ascii_uppercase().to_string() + chars.as_str()
    })
}

fn argb(s: &DynamicScheme, src: Src) -> u32 {
    let st = status(s);
    match src {
        Src::Role(role) => s.argb(role),
        Src::Success => st.success.color,
        Src::OnSuccess => st.success.on_color,
        Src::Warning => st.warning.color,
        Src::OnWarning => st.warning.on_color,
    }
}

fn color_json(argb: u32) -> String {
    let (r, g, b) = rgb(argb);
    format!(
        "{{\n        \"color-space\" : \"srgb\",\n        \"components\" : {{\n          \"alpha\" : \"1.000\",\n          \"blue\" : \"0x{b:02X}\",\n          \"green\" : \"0x{g:02X}\",\n          \"red\" : \"0x{r:02X}\"\n        }}\n      }}"
    )
}

const INFO: &str = "  \"info\" : {\n    \"author\" : \"xcode\",\n    \"version\" : 1\n  }\n";

fn colorset(schemes: &[(&str, &DynamicScheme); 4], src: Src) -> String {
    let mut out = String::from("{\n  \"colors\" : [\n");
    for (i, (appearances, scheme)) in schemes.iter().enumerate() {
        out.push_str("    {\n");
        if !appearances.is_empty() {
            let _ = writeln!(out, "      \"appearances\" : [{appearances}],");
        }
        let _ = writeln!(out, "      \"color\" : {},", color_json(argb(scheme, src)));
        out.push_str("      \"idiom\" : \"universal\"\n    }");
        out.push_str(if i + 1 == schemes.len() { "\n" } else { ",\n" });
    }
    out.push_str("  ],\n");
    out.push_str(INFO);
    out.push_str("}\n");
    out
}

const DARK: &str = "\n        {\n          \"appearance\" : \"luminosity\",\n          \"value\" : \"dark\"\n        }\n      ";
const HIGH: &str = "\n        {\n          \"appearance\" : \"contrast\",\n          \"value\" : \"high\"\n        }\n      ";
const DARK_HIGH: &str = "\n        {\n          \"appearance\" : \"luminosity\",\n          \"value\" : \"dark\"\n        },\n        {\n          \"appearance\" : \"contrast\",\n          \"value\" : \"high\"\n        }\n      ";

/// Swift identifiers that are keywords and must be escaped with backticks.
const SWIFT_KEYWORDS: [&str; 4] = ["default", "extension", "protocol", "static"];

fn swift_ident(name: &str) -> String {
    if SWIFT_KEYWORDS.contains(&name) {
        format!("`{name}`")
    } else {
        name.to_owned()
    }
}

fn swift_file(src: &ThemeSource, catalog: &str) -> String {
    let pascal = src.pascal();
    let mut out = format!(
        "// Generated by yolo-emit for {} from yolo-tokens roles. Do not hand-edit.\n// Add {catalog} to the target; every color resolves light, dark and Increase Contrast.\nimport SwiftUI\n#if canImport(AppKit)\nimport AppKit\n#endif\n\npublic extension Color {{\n    /// {} color roles from {catalog}.\n    enum {pascal} {{\n",
        src.name, src.name
    );
    for (asset, ident, _) in entries() {
        let _ = writeln!(
            out,
            "        public static let {} = Color(\"{asset}\")",
            swift_ident(&ident)
        );
    }
    out.push_str("    }\n}\n\n#if canImport(AppKit)\n");
    let _ = write!(
        out,
        "/// AppKit appearances each asset catalog variant is selected for.\npublic enum {pascal}Appearance {{\n    public static let light = NSAppearance.Name.aqua\n    public static let dark = NSAppearance.Name.darkAqua\n    public static let highContrastLight = NSAppearance.Name.accessibilityHighContrastAqua\n    public static let highContrastDark = NSAppearance.Name.accessibilityHighContrastDarkAqua\n}}\n#endif\n"
    );
    out
}

/// Swift file, catalog root `Contents.json`, then one `Contents.json` per colorset.
#[must_use]
pub fn files(src: &ThemeSource) -> Vec<EmittedFile> {
    let catalog = format!("{}.xcassets", src.pascal());
    let light_hc = src.high_contrast(false);
    let dark_hc = src.high_contrast(true);
    let schemes: [(&str, &DynamicScheme); 4] = [
        ("", &src.light),
        (DARK, &src.dark),
        (HIGH, &light_hc),
        (DARK_HIGH, &dark_hc),
    ];
    let mut out = vec![
        EmittedFile::new(
            format!("{}Colors.swift", src.pascal()),
            swift_file(src, &catalog),
        ),
        EmittedFile::new(
            format!("{catalog}/Contents.json"),
            format!("{{\n{INFO}}}\n"),
        ),
    ];
    for (asset, _, source) in entries() {
        out.push(EmittedFile::new(
            format!("{catalog}/{asset}.colorset/Contents.json"),
            colorset(&schemes, source),
        ));
    }
    out
}
