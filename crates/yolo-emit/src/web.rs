//! Web targets: `--md-sys-color-*` custom properties and a Tailwind CSS v4 `@theme` sheet.
//!
//! Both sheets resolve the mode three ways: the OS preference (`prefers-color-scheme`), and an
//! explicit `data-theme="light"` / `data-theme="dark"` attribute that overrides it.

use crate::extended::status;
use crate::{BYRON_LOVE_PALETTE, BYRON_LOVE_PET_SPEC, ROLES, ThemeSource, c, hex};
use crate::{HYPRLAND_DECORATION_SPEC, OMARCHY_THEMES};
use std::fmt::Write;
use yolo_shared::{OmarchySubTheme, YoloThemePreset};
use yolo_tokens::scheme::DynamicScheme;

fn color_block(out: &mut String, s: &DynamicScheme, indent: &str) {
    for &role in ROLES {
        let _ = writeln!(
            out,
            "{indent}--md-sys-color-{}: {};",
            role.name(),
            c(s, role)
        );
    }
    let st = status(s);
    for (name, g) in [("success", st.success), ("warning", st.warning)] {
        let _ = writeln!(out, "{indent}--md-sys-color-{name}: {};", hex(g.color));
        let _ = writeln!(
            out,
            "{indent}--md-sys-color-on-{name}: {};",
            hex(g.on_color)
        );
        let _ = writeln!(
            out,
            "{indent}--md-sys-color-{name}-container: {};",
            hex(g.container)
        );
        let _ = writeln!(
            out,
            "{indent}--md-sys-color-on-{name}-container: {};",
            hex(g.on_container)
        );
    }
}

/// Light defaults, OS dark preference, and `data-theme` overrides.
fn mode_blocks(out: &mut String, src: &ThemeSource) {
    out.push_str(":root,\n[data-theme=\"light\"] {\n  color-scheme: light;\n");
    color_block(out, &src.light, "  ");
    out.push_str("}\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {\n    color-scheme: dark;\n");
    color_block(out, &src.dark, "    ");
    out.push_str("  }\n}\n[data-theme=\"dark\"] {\n  color-scheme: dark;\n");
    color_block(out, &src.dark, "  ");
    out.push_str("}\n");
}

/// `m3-colors.css`.
#[must_use]
pub fn css(src: &ThemeSource) -> String {
    let mut out = format!(
        "/* Generated by yolo-emit for {} from yolo-tokens roles. Do not hand-edit. */\n",
        src.name
    );
    mode_blocks(&mut out, src);
    if let Some(preset) = src.preset {
        preset_block(&mut out, preset);
    }
    out
}

/// Preset structure and signature tokens (radii, blur, brand palettes) as custom properties.
fn preset_block(out: &mut String, preset: YoloThemePreset) {
    let dark_tokens = preset.tokens(true);
    let style = preset.style();
    let _ = writeln!(
        out,
        "/* YoloThemePreset: {} ({}) */\n:root {{\n  --yolo-theme-preset: \"{}\";\n  --yolo-theme-seed: {};\n  --yolo-bg-primary: {};\n  --yolo-bg-surface: {};\n  --yolo-bg-elevated: {};\n  --yolo-text-primary: {};\n  --yolo-text-secondary: {};\n  --yolo-accent-primary: {};\n  --yolo-accent-secondary: {};\n  --yolo-border-subtle: {};\n  --yolo-radius-sm: {}px;\n  --yolo-radius-md: {}px;\n  --yolo-radius-lg: {}px;\n  --yolo-backdrop-blur: {}px;\n  --yolo-window-vibrancy: {};",
        preset.id(),
        preset.display_name(),
        preset.id(),
        preset.seed_hex(),
        dark_tokens.bg_primary,
        dark_tokens.bg_surface,
        dark_tokens.bg_elevated,
        dark_tokens.text_primary,
        dark_tokens.text_secondary,
        dark_tokens.accent_primary,
        dark_tokens.accent_secondary,
        dark_tokens.border_subtle,
        style.radius_sm_px,
        style.radius_md_px,
        style.radius_lg_px,
        style.backdrop_blur_px,
        style.window_vibrancy,
    );
    if preset == YoloThemePreset::Omarchy {
        let p = OmarchySubTheme::TokyoNight.spec();
        let _ = writeln!(
            out,
            "  --omarchy-subtheme: \"{}\";\n  --omarchy-subtheme-count: {};\n  --t-bg: {};\n  --t-surface: {};\n  --t-brand: {};\n  --t-accent-cyan: {};\n  --t-accent-purple: {};\n  --t-border-subtle: {};",
            p.id,
            OMARCHY_THEMES.len(),
            p.background,
            p.lighter_background,
            p.accent,
            p.cyan,
            p.accent_secondary,
            p.muted_border,
        );
    }
    if preset == YoloThemePreset::Hyprland {
        let h = HYPRLAND_DECORATION_SPEC;
        let _ = writeln!(
            out,
            "  --hypr-active-border-start: {};\n  --hypr-active-border-end: {};\n  --hypr-active-border-angle: {}deg;\n  --hypr-inactive-border: {};\n  --hypr-rounding: {}px;\n  --hypr-blur-size: {};\n  --hypr-blur-passes: {};",
            h.active_border_start_hex,
            h.active_border_end_hex,
            h.active_border_angle_deg,
            h.inactive_border_rgba,
            h.rounding_px,
            h.kawase_blur_size,
            h.kawase_blur_passes,
        );
    }
    if preset == YoloThemePreset::Aphrody {
        for teinte in BYRON_LOVE_PALETTE {
            let _ = writeln!(out, "  --byron-love-{}: {};", teinte.id, teinte.hex);
        }
        let _ = writeln!(
            out,
            "  --aphrody-celestial-gold: {};\n  --aphrody-divine-violet: {};\n  --aphrody-divine-cyan: {};\n  --aphrody-pet-id: \"{}\";",
            BYRON_LOVE_PET_SPEC.celestial_gold_hex,
            BYRON_LOVE_PET_SPEC.divine_violet_hex,
            BYRON_LOVE_PET_SPEC.divine_cyan_hex,
            BYRON_LOVE_PET_SPEC.pet_id,
        );
    }
    out.push_str("}\n");
}

/// Names of the status color tokens added next to the Material roles.
const STATUS_NAMES: [&str; 8] = [
    "success",
    "on-success",
    "success-container",
    "on-success-container",
    "warning",
    "on-warning",
    "warning-container",
    "on-warning-container",
];

/// `tailwind.css` for Tailwind CSS v4: import it after `@import "tailwindcss";`.
///
/// Utilities such as `bg-primary`, `text-on-surface` and `border-outline-variant` follow the
/// active mode because the `@theme inline` block maps each `--color-*` token to the
/// mode-switched `--md-sys-color-*` property. `dark:` variants follow `data-theme="dark"`.
#[must_use]
pub fn tailwind(src: &ThemeSource) -> String {
    let mut out = format!(
        "/* Generated by yolo-emit for {} (Tailwind CSS v4) from yolo-tokens roles. Do not hand-edit. */\n@custom-variant dark (&:where([data-theme=\"dark\"], [data-theme=\"dark\"] *));\n",
        src.name
    );
    mode_blocks(&mut out, src);
    out.push_str("@theme inline {\n");
    for &role in ROLES {
        let _ = writeln!(out, "  --color-{0}: var(--md-sys-color-{0});", role.name());
    }
    for name in STATUS_NAMES {
        let _ = writeln!(out, "  --color-{name}: var(--md-sys-color-{name});");
    }
    if let Some(style) = src.style() {
        let xs = (style.radius_sm_px / 2.0).round();
        let _ = writeln!(
            out,
            "  --radius-xs: {xs}px;\n  --radius-sm: {}px;\n  --radius-md: {}px;\n  --radius-lg: {}px;\n  --radius-xl: {}px;\n  --spacing: {}px;",
            style.radius_sm_px,
            style.radius_md_px,
            style.radius_lg_px,
            style.radius_lg_px * 1.5,
            style.spacing_grid_px,
        );
    }
    out.push_str("}\n");
    out
}
